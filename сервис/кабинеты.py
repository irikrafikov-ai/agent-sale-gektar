def кабинет(ключ: str) -> dict:
    if ключ not in КАБИНЕТЫ:
        raise KeyError(f"неизвестный кабинет {ключ!r}, есть: {', '.join(КАБИНЕТЫ)}")
    return {**КАБИНЕТЫ[ключ], "ключ": ключ}


def по_user_id(user_id: str | int | None) -> dict | None:
    """Маршрутизация события вебхука. В payload Авито user_id — ВЛАДЕЛЕЦ
    кабинета, а не собеседник; author_id это другое поле."""
    if user_id is None:
        return None
    for ключ, данные in КАБИНЕТЫ.items():
        if данные["avito_user_id"] == str(user_id):
            return {**данные, "ключ": ключ}
    return None


def настроен(каб: dict) -> bool:
    return all(os.environ.get(п) for п in каб["переменные"])
