@app.post("/avito/{secret}")
async def приём(secret: str, request: Request, фон: BackgroundTasks) -> Response:
    """Принять и немедленно ответить: у нас есть две секунды, не больше.

    Вся работа уходит в фон. Авито при отсутствии 200 OK повторяет доставку,
    а повтор здесь означает второе сообщение клиенту.
    """
    if СЕКРЕТ and secret != СЕКРЕТ:
        лог("отвергнут запрос с чужим секретом")
        return Response(status_code=404)

    try:
        тело = await request.json()
    except Exception:  # noqa: BLE001
        сырое = (await request.body()).decode("utf-8", "replace")
        лог("тело не разобралось как JSON:", сырое[:500])
        return Response(status_code=200)

    # Печатаем сырое событие целиком: схему payload Авито не публикует, и это
    # единственный способ увидеть её настоящую форму на живом трафике.
    лог("событие:", json.dumps(тело, ensure_ascii=False)[:1000])

    chat_id = найти_chat_id(тело)
    if not chat_id:
        лог("chat_id в событии не найден — пропускаю")
        return Response(status_code=200)

    каб = реестр.по_user_id(найти_user_id(тело))
    if каб is None:
        лог(chat_id, "— событие из НЕИЗВЕСТНОГО кабинета, не трогаю")
        return Response(status_code=200)

    фон.add_task(разобрать, chat_id, каб)
    return Response(status_code=200)


