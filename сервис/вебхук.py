def найти_chat_id(данные: Any) -> str | None:
    """Достаёт chat_id из любой вложенности, не полагаясь на форму payload.

    Обход в ширину, а не рекурсия по известным ключам: если Авито переложит
    поле на уровень выше или ниже, вебхук продолжит работать.
    """
    очередь: deque[Any] = deque([данные])
    while очередь:
        узел = очередь.popleft()
        if isinstance(узел, dict):
            for ключ, значение in узел.items():
                if ключ in ("chat_id", "chatId") and isinstance(значение, str) and значение:
                    return значение
                очередь.append(значение)
        elif isinstance(узел, list):
            очередь.extend(узел)
    return None


