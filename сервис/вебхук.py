ДУБЛЬ_НА = re.compile(r"ДУБЛЬ\s+СДЕЛКИ\s+(\d+)")


def _цель_дубля(название_upper: str) -> str | None:
    """Номер сделки, на которую указывает пометка «ДУБЛЬ сделки N»."""
    совпадение = ДУБЛЬ_НА.search(название_upper)
    return совпадение.group(1) if совпадение else None


def _сделка_жива(ид: str) -> tuple[bool, str]:
    """Активна ли сделка, в которую слили дубль.

    Не смогли проверить — считаем мёртвой: неоднозначность всегда трактуется
    не в пользу отправки, как и во всей этой функции.
    """
    try:
        карточка = bitrix().crm_get("deal", ид)
    except Exception as ошибка:  # noqa: BLE001
        return False, f"оригинал {ид} не прочитался: {ошибка}"

    название = (карточка.get("TITLE") or "").upper()
    стадия = карточка.get("STAGE_ID") or ""
    if стадия.endswith("LOSE") or "ОТКАЗ" in название:
        return False, f"оригинал {ид} тоже закрыт ({карточка.get('TITLE')} / {стадия})"
    return True, f"оригинал {ид} в работе ({стадия})"


def _сделка_по_чату(chat_id: str) -> dict | None:
    """Карточка, привязанная к этому чату через ORIGIN_ID.

    Единственный ТОЧНЫЙ способ найти сделку клиента. Сопоставление по имени
    неизбежно врёт: 01.09 в воронке нашлось 23 открытых сделки «Александр»
    и 13 «Дмитрий», а подстрока «Aleksa» подтянула чужую карточку
    «Aleksandr Nikolaevich». Поэтому чат решает, а имя — только запасной путь.
    """
    try:
        сделки = bitrix().crm_list(
            "deal",
            filter={"ORIGIN_ID": chat_id},
            select=["ID", "TITLE", "STAGE_ID"],
            limit=1,
        )
    except Exception:  # noqa: BLE001 — сеть Битрикса решает вызывающий
        return None
    return сделки[0] if сделки else None


def битрикс_запрещает(имя: str, chat_id: str = "") -> tuple[bool, str]:
    """Шаг 2.0 рабочего цикла: отказникам и дублям не пишем.

    Авито не знает, что человек уже отказался, — знает только Битрикс. Именно
    на этом 12.08 сломался разговор с Максом: сделка 2065 стояла ОТКАЗ, а в
    чате последнее слово было за клиентом, и текст напрашивался сам.

    Сопоставление по имени неточное, поэтому неоднозначность трактуется не в
    пользу отправки: вернём «запрещает» и отдадим чат агенту, у него есть чем
    разобраться. Лучше ответить через минуту, чем через секунду не тому.
    """
    # Карточка, привязанная к ЭТОМУ чату, отвечает на вопрос однозначно —
    # ни имени, ни эвристик не нужно. Закрыта у нас = не пишем; в работе =
    # пишем, даже если у тёзки в воронке стоит отказ.
    if chat_id:
        своя = _сделка_по_чату(chat_id)
        if своя:
            название = (своя.get("TITLE") or "").upper()
            стадия = своя.get("STAGE_ID") or ""
            закрыта = стадия.endswith("LOSE") or "ОТКАЗ" in название or "МОЛЧУН" in название
            if закрыта:
                return True, f"сделка {своя.get('ID')} по этому чату закрыта ({стадия})"
            return False, f"сделка {своя.get('ID')} по этому чату в работе"

    имя = (имя or "").strip()
    if not имя:
        return True, "имя клиента не определилось"

    try:
        сделки = bitrix().crm_list(
            "deal",
            filter={"CATEGORY_ID": 0, "%TITLE": имя},
            select=["ID", "TITLE", "STAGE_ID"],
        )
    except Exception as ошибка:  # noqa: BLE001 — сеть Битрикса не должна ронять вебхук
        return True, f"Битрикс недоступен: {ошибка}"

    if not сделки:
        return False, "сделок нет — клиент новый"

    for сделка in сделки:
        название = (сделка.get("TITLE") or "").upper()
        стадия = сделка.get("STAGE_ID") or ""
        if not ("ОТКАЗ" in название or "ДУБЛЬ" in название or стадия.endswith("LOSE")):
            continue

        # Пометка «ДУБЛЬ сделки N» — служебная запись, а не отказ клиента.
        # LOSE на ней стоит потому, что карточку убрали из работы, а не потому,
        # что человек сказал «нет». Смотреть надо на ту сделку, которая выжила.
        #
        # 22.08 в 12:27 на этом встал Максим: сделка 2073 «ДУБЛЬ сделки 1965 /
        # LOSE» заблокировала ответ, а сама 1965 всё это время стояла в NEW —
        # клиент активен и никем не забракован. Сигнал провисел пять часов.
        выживший = _цель_дубля(название)
        if выживший:
            жив, пояснение = _сделка_жива(выживший)
            if жив:
                continue  # оригинал в работе — блокировать нечего
            return True, f"сделка {сделка.get('ID')} → дубль {выживший}: {пояснение}"

        return True, f"сделка {сделка.get('ID')} — {сделка.get('TITLE')} / {стадия}"

    if len(сделки) > 1:
        return True, f"{len(сделки)} сделок по имени — неоднозначно"

    return False, f"сделка {сделки[0].get('ID')} активна"


def обеспечить_сделку(chat_id: str, каб: dict, имя: str, повод: str) -> None:
    """Лид должен попасть в Битрикс, даже если агент не проснётся.

    По Берегам сделку создаёт открытая линия Битрикса — площадка делает это
    сама, в ту же секунду. По Долине открытой линии НЕТ, и до 25.08 сделку
    заводил только агент. В тот день агент упал на сборке брифа, и «ДрайвМаркет»
    не попал в CRM вообще: вебхук отработал за секунду, лид всё равно потерялся.

    Вебхук получает событие раньше агента и не падает вместе с ним — значит
    заводить сделку должен он. Агент дальше работает с готовой карточкой.

    Идемпотентность держится на ORIGIN_ID = chat_id: сколько бы событий ни
    пришло по одному чату, сделка создастся один раз. Это штатное поле Битрикса
    для внешних идентификаторов, и по нему можно фильтровать.
    """
    if not каб.get("сделку_заводит_вебхук"):
        return  # здесь работает открытая линия, дубли не нужны

    try:
        есть = bitrix().crm_list(
            "deal",
            filter={"ORIGIN_ID": chat_id},
            select=["ID"],
            limit=1,
        )
        if есть:
            return

        # Открытая линия могла успеть раньше нас. Она не ставит ORIGIN_ID, зато
        # называет сделку «Имя — Открытая линия» и создаёт её за секунды. Ищем
        # такую по имени клиента среди свежих — если нашлась, значит канал уже
        # подключён и наша подстраховка больше не нужна.
        #
        # Сопоставление по имени в общем случае ненадёжно, но здесь окно узкое:
        # четверть часа и только карточки открытой линии. Цена ошибки — что мы
        # не заведём свою сделку, хотя карточка чужая; она всё равно появится
        # на следующем сообщении клиента.
        свежие = bitrix().crm_list(
            "deal",
            filter={
                "CATEGORY_ID": каб.get("категория_битрикс", 0),
                "%TITLE": "Открытая линия",
                ">=DATE_CREATE": (datetime.now(МСК) - timedelta(minutes=15)).strftime("%Y-%m-%dT%H:%M:%S"),
            },
            select=["ID", "TITLE"],
            limit=20,
        )
        своя = [д for д in свежие if имя and имя.lower() in (д.get("TITLE") or "").lower()]
        if своя:
            лог(chat_id, f"— сделку {своя[0]['ID']} уже создала открытая линия, не дублирую")
            в_отчёт(
                f"✅ Открытая линия сработала по «{каб['название']}»: сделка "
                f"{своя[0]['ID']} создана Битриксом, не мной.\n\n"
                "Значит канал подключён и мои подстраховки по этому кабинету "
                "пора выключить — скажите, сниму флаги "
                "«сделку_заводит_вебхук» и зеркалирование переписки, чтобы не "
                "было двойных карточек и двойных комментариев.",
                alert=True,
            )
            return

        ид = bitrix().crm_add(
            "deal",
            {
                "TITLE": f"{имя or 'без имени'} {datetime.now(МСК):%d.%m.%Y} ({каб['название']}, Авито)",
                "CATEGORY_ID": каб.get("категория_битрикс", 0),
                "STAGE_ID": "NEW",
                "SOURCE_ID": "1|AVITO",
                "ASSIGNED_BY_ID": 1,
                "ORIGINATOR_ID": "avito",
                "ORIGIN_ID": chat_id,
                "COMMENTS": (
                    f"Чат Авито (кабинет {каб['ключ']}): {chat_id}\n"
                    f"Повод: {повод}\n\n"
                    "Сделку завёл вебхук, до разбора агентом: у этого кабинета "
                    "нет открытой линии Битрикса, и без этого лид не попал бы "
                    "в CRM вовсе, если бы агент не поднялся."
                ),
            },
        )
        лог(chat_id, f"— завёл сделку {ид} в Битриксе")
    except Exception as ошибка:  # noqa: BLE001 — Битрикс не должен ронять ответ клиенту
        лог(chat_id, f"— сделку завести НЕ смог: {type(ошибка).__name__}: {ошибка}")
        try:
            в_отчёт(
                f"⚠️ Лид не попал в Битрикс: чат {chat_id} ({каб['название']}).\n"
                f"Ошибка: {ошибка}\n\nЗаведите карточку вручную — клиенту "
                "отвечаем, но в CRM его нет.",
                alert=True,
            )
        except Exception:  # noqa: BLE001
            pass


def зеркалить_сообщение(chat_id: str, каб: dict, сообщение: dict, наш_id: int) -> None:
    """Переписка в карточке сделки — то, ради чего нужна открытая линия.

    Подключить второй авито-канал к открытой линии Битрикса из кода нельзя:
    imconnector.list и imconnector.status отвечают «Current authorization type
    is denied … Application context required» — методы закрыты для входящего
    вебхука и требуют контекста приложения. В интерфейсе это делается через
    авторизацию в Авито, то есть чужими учётными данными.

    Но открытая линия даёт три вещи, и две из них мы уже закрыли сами:
    заведение сделки делает вебхук, отвечает агент через API Авито. Оставалась
    третья — видеть переписку в карточке. Её и зеркалим.

    Только для кабинетов без открытой линии: у Берегов это делает Битрикс, и
    вторая копия там была бы мусором.
    """
    if not каб.get("сделку_заводит_вебхук"):
        return

    try:
        сделки = bitrix().crm_list(
            "deal", filter={"ORIGIN_ID": chat_id}, select=["ID"], limit=1
        )
        if not сделки:
            return  # карточки ещё нет — обеспечить_сделку заведёт её следом

        текст_ = (текст(сообщение) or сообщение.get("type", "")).strip()
        if not текст_:
            return

        наше = исходящее(сообщение, наш_id)
        кто = "↩️ Мы" if наше else "💬 Клиент"
        момент = datetime.fromtimestamp(
            сообщение.get("created", 0) or datetime.now(МСК).timestamp(), МСК
        )
        bitrix().timeline_comment_add(
            сделки[0]["ID"],
            f"[B]{кто} · {момент:%d.%m %H:%M}[/B]\n{текст_[:1500]}",
        )
    except Exception as ошибка:  # noqa: BLE001 — зеркало не должно мешать ответу
        лог(chat_id, f"— переписку в карточку не записал: {type(ошибка).__name__}: {ошибка}")


def записать_в_битрикс(имя: str, chat_id: str, каб: dict, отправленный_текст: str) -> None:
    """Комментарий в таймлайн. Не смогли — не молчим, а говорим в Телеграм.

    Регламент: если действия нет в Битриксе, его не было. Префикс
    «📤 ОТПРАВЛЕНО» обязателен дословно — по нему контроль качества считает
    полноту таймлайна (код B05).
    """
    момент = datetime.now(МСК).strftime("%d.%m.%Y %H:%M")
    комментарий = (
        f"📤 ОТПРАВЛЕНО {момент} · Авито ({каб['название']}) · чат {chat_id}\n"
        f"Первое касание. Повод: клиент открыл спецусловия (системный триггер Авито).\n\n"
        f"{отправленный_текст}\n\n"
        f"Логика: отправлено вебхуком в первую минуту после триггера, без прогона — "
        f"клиент в этот момент в приложении. Текст фиксированный, по рабочему циклу, шаг 3.\n"
        f"Следующий шаг: ответит — квалификация; промолчит — цепочка касаний."
    )
    try:
        сделки = bitrix().crm_list(
            "deal",
            filter={"CATEGORY_ID": 0, "%TITLE": имя},
            select=["ID", "TITLE"],
        )
        if not сделки:
            лог(chat_id, "⚠️ сделки в Битриксе нет — комментарий записать некуда")
            return
        bitrix().timeline_comment_add(сделки[0]["ID"], комментарий)
        лог("битрикс: комментарий в сделку", сделки[0]["ID"])
    except Exception as ошибка:  # noqa: BLE001
        лог(chat_id, "⚠️ шаблон ушёл, но комментарий не записался:", ошибка)


