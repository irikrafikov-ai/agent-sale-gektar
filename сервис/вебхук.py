async def разобрать(chat_id: str, каб: dict) -> None:
    замок = _замки.setdefault(chat_id, asyncio.Lock())
    if замок.locked():
        лог(chat_id, "— уже в работе, пропускаю")
        return

    async with замок:
        try:
            await asyncio.to_thread(разобрать_синхронно, chat_id, каб)
        except Exception as ошибка:  # noqa: BLE001 — вебхук не имеет права падать
            лог(chat_id, "ОШИБКА:", ошибка)
            try:
                в_отчёт(f"❌ Вебхук споткнулся на чате {chat_id}: {ошибка}", alert=True)
            except Exception:  # noqa: BLE001 — Телеграм не должен маскировать исходную ошибку
                pass


def разобрать_синхронно(chat_id: str, каб: dict) -> None:
    # Кабинет не настроен — молчим. Это штатное состояние «Светлой долины»,
    # пока Ирик не задал AVITO2_* и не утвердил тексты. Ответить фактами
    # «Щёкинских берегов» человеку, который спрашивает про гектар в Тверской
    # области, хуже, чем не ответить вовсе.
    if not реестр.настроен(каб):
        лог(chat_id, f"— кабинет «{каб['название']}» не настроен, пропускаю")
        return

    клиент = клиент_кабинета(каб)
    наш_id = клиент.user_id
    сообщения = клиент.chat_messages(chat_id, limit=50)
    if not сообщения:
        лог(chat_id, "— пустой чат")
        return

    последнее = сообщения[0]
    ключ = str(последнее.get("id") or "")
    if ключ and ключ in _обработанные:
        лог(chat_id, "— повторная доставка, пропускаю")
        return
    if ключ:
        _обработанные.append(ключ)

    # Зеркалим сообщение в карточку — до всех проверок и решений. Наши реплики
    # тоже: без них в карточке останутся одни вопросы клиента без ответов.
    # Работает только у кабинетов без открытой линии, у Берегов это делает
    # Битрикс сам.
    зеркалить_сообщение(chat_id, каб, последнее, наш_id)

    # Своё же сообщение. Без этой проверки вебхук отвечает сам себе по кругу:
    # отправили — Авито прислало событие — снова отправили.
    if исходящее(последнее, наш_id):
        лог(chat_id, "— последнее сообщение наше, ничего не делаю")
        return

    писали_ли_мы = any(исходящее(с, наш_id) for с in сообщения)
    шаблон_уже_стоит = any(
        след_шаблона(каб) in текст(с) for с in сообщения if исходящее(с, наш_id)
    )
    тело = текст(последнее).lower()
    пустой_чат = any(т in тело for т in ПУСТОЙ_ЧАТ)
    это_триггер = any(т in тело for т in ТРИГГЕРЫ) or пустой_чат
    системное = последнее.get("type") == "system"

    лог(
        chat_id,
        f"| триггер={это_триггер} системное={системное}",
        f"писали={писали_ли_мы} шаблон={шаблон_уже_стоит}",
        f"| {тело[:70]!r}",
    )

    # Системное сообщение не из нашей тройки — отзыв, звонок, что-то ещё.
    # Будить модель незачем: отвечать не на что.
    if системное and not это_триггер:
        # Молчать о незнакомом системном сообщении опасно: за два дня фильтр
        # трижды не знал очередной формулировки Авито, и каждый раз это
        # выяснялось только когда Ирик сам замечал непрочитанный чат.
        # Признак «нам предлагают написать первыми» есть во всех трёх фразах.
        if "первое сообщение" in тело or "напишите" in тело:
            лог(chat_id, "— НЕИЗВЕСТНЫЙ системный сигнал, но Авито зовёт писать → агенту")
            в_отчёт(
                f"❓ Новая формулировка системного сообщения Авито, чат {chat_id}:\n\n"
                f"«{текст(последнее)[:300]}»\n\n"
                "Отдал агенту. Если формулировка рабочая — добавь её в ТРИГГЕРЫ или ПУСТОЙ_ЧАТ.",
                alert=True,
            )
            разбудить_агента(chat_id, "неизвестный системный сигнал Авито, зовут написать первыми", каб)
            return
        лог(chat_id, "— системное сообщение вне триггеров, пропускаю")
        return

    # Открыл чат и промолчал → тот же утверждённый шаблон, мгновенно.
    #
    # Я предлагал будить агента: первая строка шаблона говорит «Вы смотрели
    # спецусловия по участку», а этот человек их не смотрел. Ирик 21.08
    # решил иначе — отправлять дословно, без правок. Причина весомее моей
    # придирки: шаблон уходит за секунды, агент думает полторы минуты, а
    # человек в этот момент сидит в открытом чате и ждёт. Единый текст
    # первого касания к тому же не расползается по вариантам.
    if пустой_чат:
        if писали_ли_мы or шаблон_уже_стоит:
            лог(chat_id, "— чат без слов клиента, но мы уже писали, пропускаю")
            return
        отправить_шаблон(chat_id, каб)
        return

    # Прямой сигнал Авито о готовности покупать — Ирик узнаёт немедленно,
    # не дожидаясь отчёта. Алерт уходит до отправки: если дальше что-то
    # сорвётся, лид всё равно не потеряется.
    if ГОТОВНОСТЬ_К_ПОКУПКЕ in тело:
        сообщить_о_тёплом(chat_id, "системный сигнал Авито: «выразил готовность к покупке»", каб)

    # Быстрая дорога: триггер, диалога ещё не было, шаблон не отправлялся.
    if это_триггер and not писали_ли_мы and not шаблон_уже_стоит:
        отправить_шаблон(chat_id, каб)
        return

    # Триггер, но шаблон уже стоит. Повторять нельзя — человек получит одно и
    # то же дважды. Следующий ход осмысленный, значит нужен агент.
    if это_триггер and шаблон_уже_стоит:
        лог(chat_id, "— триггер повторный, шаблон уже стоит → агенту")
        разбудить_агента(chat_id, "повторный триггер спецусловий, шаблон уже отправлен", каб)
        return

    if это_триггер:
        разбудить_агента(chat_id, "триггер спецусловий в чате, где диалог уже шёл", каб)
        return

    # Живой текст клиента — думать надо, шаблоном не отделаться.
    разбудить_агента(chat_id, "клиент написал сообщение", каб)


def отправить_шаблон(chat_id: str, каб: dict) -> None:
    шаблон = каб["шаблон"]
    if not шаблон:
        # У кабинета нет утверждённого текста первого касания. Сочинять его
        # на ходу нельзя: первое сообщение — самое результативное в аккаунте,
        # и его формулировки Ирик утверждает дословно. Отдаём агенту.
        лог(chat_id, f"— у кабинета «{каб['название']}» нет утверждённого шаблона → агенту")
        разбудить_агента(chat_id, "триггер спецусловий, утверждённого шаблона нет", каб)
        return

    имя = имя_клиента(chat_id, каб)

    if not темп_позволяет():
        telegram().send(
            f"🛑 Стоп-кран темпа: за час уже {ПРЕДЕЛ_В_ЧАС} сообщений. "
            f"Чат {chat_id} ({имя}) не тронут, жду решения.",
            alert=True,
        )
        return

    запрет, причина = битрикс_запрещает(имя, chat_id)
    if запрет:
        лог(chat_id, "— Битрикс не разрешает:", причина, "→ агенту")
        разбудить_агента(chat_id, f"триггер спецусловий, но {причина}", каб)
        return

    прошлый = прошлый_диалог(chat_id, каб)
    if прошлый:
        лог(chat_id, "— с клиентом уже был диалог в чате", прошлый, "→ агенту")
        разбудить_агента(
            chat_id,
            f"новый чат, но с этим клиентом уже был диалог в чате {прошлый} — "
            "перечитай его, шаблон не дублируй, продолжи разговор с учётом истории",
            каб,
        )
        return

    if РЕЖИМ != "send":
        лог(chat_id, "— режим", РЕЖИМ, ": шаблон НЕ отправлен")
        return

    # Стандарт Ирика 27.08: первое касание — два коротких сообщения подряд.
    # Первое — тур с легендой, второе — «Открылась ссылка?». Вопрос отдельным
    # сообщением работает как микро-подтверждение: человеку проще ответить
    # «да» на короткую реплику, чем реагировать на полотно с ценами.
    кли = клиент_кабинета(каб)
    кли.send_message(chat_id, шаблон)
    _отправки.append(time.time())
    try:
        кли.send_message(chat_id, реестр.ШАБЛОН_ВОПРОС)
        _отправки.append(time.time())
    except Exception as ошибка:  # noqa: BLE001 — тур уже ушёл, это главное
        лог(chat_id, "⚠️ вопрос-подтверждение не ушёл:", ошибка)
    лог(chat_id, "✅ шаблон отправлен (тур + вопрос)")

    записать_в_битрикс(имя, chat_id, каб, шаблон)


def сообщить_о_тёплом(chat_id: str, признак: str, каб: dict) -> None:
    """Алерт Ирику о тёплом лиде — регламент 03, указание от 17.08.

    Уходит в ту же минуту, что и событие, а не в вечернем отчёте: к вечеру
    интерес остывает, и особый контроль применять уже не к кому.

    Ошибка Телеграма здесь не должна отменять ответ клиенту — он дороже алерта,
    поэтому исключение гасится и попадает только в лог.
    """
    имя = имя_клиента(chat_id, каб)
    try:
        telegram().send(
            f"🔥 *ТЁПЛЫЙ ЛИД* — {имя or 'без имени'}\n"
            f"Проект: {каб['название']}\n\n"
            f"Признак: {признак}\n"
            f"Чат: `{chat_id}`\n\n"
            f"Отвечаю сам, диалог продолжаю. От вас — особый контроль.",
            alert=True,
        )
        лог(chat_id, "🔥 алерт о тёплом лиде отправлен:", признак)
    except Exception as ошибка:  # noqa: BLE001
        лог(chat_id, "алерт о тёплом лиде не ушёл:", ошибка)


def прошлый_диалог(chat_id: str, каб: dict) -> str:
    """Другой чат этого же человека, где разговор уже шёл.

    Один человек часто пишет с двух-трёх объявлений, и слепой шаблон во
    второй чат вручает ему ту же презентацию ещё раз — правило Ирика
    29.08.2026: перед первым сообщением искать прошлый диалог. Ошибка поиска
    не должна глушить первое касание, поэтому при сбое возвращаем «не нашли».
    """
    try:
        клиент = клиент_кабинета(каб)
        наш_id = str(клиент.user_id)
        чаты: list[dict] = []
        for сдвиг in range(0, 400, 100):
            страница = клиент.chats_list(limit=100, offset=сдвиг)
            чаты.extend(страница)
            if len(страница) < 100:
                break

        клиент_id = ""
        for чат in чаты:
            if чат.get("id") == chat_id:
                for участник in чат.get("users") or []:
                    if str(участник.get("id")) != наш_id:
                        клиент_id = str(участник.get("id"))
                break
        if not клиент_id:
            return ""

        for чат in чаты:
            if чат.get("id") == chat_id:
                continue
            участники = чат.get("users") or []
            if not any(str(у.get("id")) == клиент_id for у in участники):
                continue
            # Системное «создал чат и молчит» диалогом не считается: там
            # человек ещё ничего не читал и ничего от нас не получал.
            if (чат.get("last_message") or {}).get("type") != "system":
                return str(чат.get("id"))
    except Exception as ошибка:  # noqa: BLE001
        лог(chat_id, "поиск прошлого диалога не удался:", ошибка)
    return ""


def имя_клиента(chat_id: str, каб: dict) -> str:
    """Имя собеседника из карточки чата. Нужно для сверки с Битриксом."""
    try:
        клиент = клиент_кабинета(каб)
        наш_id = клиент.user_id
        for чат in клиент.chats_list(limit=100):
            if чат.get("id") != chat_id:
                continue
            for участник in чат.get("users") or []:
                if str(участник.get("id")) != str(наш_id):
                    return str(участник.get("name") or "")
    except Exception as ошибка:  # noqa: BLE001
        лог(chat_id, "имя не определилось:", ошибка)
    return ""


def разбудить_агента(chat_id: str, повод: str, каб: dict) -> None:
    """Живой диалог передаём агенту — здесь нужна голова, а не шаблон.

    Отдельным процессом, чтобы падение или зависание агента не утащило за
    собой веб-сервер: пока он работает, вебхук обязан принимать новые события.

    ⚠️ ЖДЁМ ЗАВЕРШЕНИЯ, и это принципиально. Раньше здесь стоял Popen без
    ожидания: процесс уходил в фон, замок чата тут же освобождался, и два
    сообщения клиента подряд поднимали ДВУХ агентов на один чат. Каждый читал
    историю, не видя ответа другого, и оба отвечали.

    21.08 в чате Владимира Жмаева это дало худший из возможных исходов: два
    наших сообщения за три секунды с ПРОТИВОРЕЧАЩИМИ вопросами — «к 9:00 или
    к 11:00?» и следом «9 или 10 утра?». Клиент получил два разных набора
    вариантов от одного собеседника. Это не опечатка, это разрушение
    ощущения, что с ним говорит человек.

    Ожидание держит замок чата до конца работы агента, поэтому второе событие
    по тому же чату дождётся своей очереди и увидит уже отправленный ответ.
    Разные чаты друг друга не блокируют — замок свой на каждый.
    """
    if РЕЖИМ != "send":
        лог(chat_id, "— режим", РЕЖИМ, ": агента не бужу.", повод)
        return

    лог(chat_id, "→ бужу агента:", повод)
    import subprocess

    # Сначала карточка, потом агент: упадёт агент — лид уже в CRM.
    обеспечить_сделку(chat_id, каб, имя_клиента(chat_id, каб), повод)

    процесс = subprocess.Popen(
        [sys.executable, str(КОРЕНЬ / "сервис" / "прогон.py"),
         "чат", chat_id, каб["ключ"], повод],
        cwd=str(КОРЕНЬ),
    )
    try:
        код = процесс.wait(timeout=ТАЙМАУТ_АГЕНТА)
        лог(chat_id, f"← агент завершился, код {код}")
    except subprocess.TimeoutExpired:
        # Зависший агент не должен держать чат вечно: снимаем его и
        # освобождаем замок, иначе клиент не получит ответа никогда.
        процесс.kill()
        лог(chat_id, f"← агент не уложился в {ТАЙМАУТ_АГЕНТА} с, снят")


