"""Вебхук Авито: реакция на событие в чате за секунды, а не за полсуток.

Зачем он вообще нужен. Прогон по расписанию отвечает клиенту в среднем через
шесть часов, а на триггере «ознакомился со спецпредложением» регламент требует
ответа в первую минуту: человек прямо сейчас в приложении. 15.08 чат с ТК Коннор
создался в 13:23, ответ ушёл в 17:24 — четыре часа, заявка остыла.

Как устроено. Авито требует 200 OK не позже двух секунд, поэтому обработчик
отвечает сразу и уходит работать в фон.

Дальше — две дороги, и разделены они намеренно:

  Быстрая. Системный триггер «ознакомился со спецпредложением» в чате, где мы
  ещё не писали. Ответ фиксированный, думать не над чем — шаблон уходит без
  участия модели, одним вызовом, за секунды. Заодно это структурно чинит
  расщепление сообщения: три отдельных сообщения вместо одного (полный текст,
  голая ссылка, голый «🟢») получались из-за трёх вызовов send_message подряд.
  Здесь вызов ровно один, повторить ту ошибку нечем.

  Медленная. Клиент написал живой текст — тут нужна голова, будится агент на
  один этот чат. Минута против двенадцати часов.

Из тела вебхука берётся ТОЛЬКО chat_id. Всё остальное перечитывается через API.
Схема payload у Авито недокументирована в открытом виде, и построить на догадке
о ней логику отправки клиенту — верный способ однажды написать не тому и не то.
"""

