async def сторожить() -> None:
    """Раз в час: не ждёт ли кто-то ответа дольше положенного.

    Живёт в вебхуке, потому что вебхук — единственный сервис, работающий
    круглосуточно. Прогоны просыпаются по расписанию и как раз могут упасть,
    а сторож должен пережить их падение — он для этого и нужен.
    """
    ЧАС = int(os.environ.get("СТОРОЖ_ИНТЕРВАЛ", "3600"))
    await asyncio.sleep(120)  # даём сервису подняться, не шумим на старте

    while True:
        try:
            # Сканируем ВСЕГДА, включая ночь: реакция на входящие — 24/7 по
            # рабочему циклу. Тихие часы касаются только алертов Ирику.
            пары: list[tuple[сторож.Забытый, dict]] = []
            for ключ in реестр.КАБИНЕТЫ:
                # Именно через реестр.кабинет(): он добавляет поле «ключ»,
                # без которого разобрать() падает KeyError. 25.08 сторож
                # нашёл троих ждущих (433, 245 и 47 минут) и уронил все три
                # разбора об эту ошибку — сырой словарь КАБИНЕТЫ ключа не
                # содержит.
                каб = реестр.кабинет(ключ)
                if not реестр.настроен(каб):
                    continue
                id_, secret = каб["переменные"]
                клиент = Avito(
                    client_id=os.environ[id_], client_secret=os.environ[secret]
                )
                try:
                    чаты = клиент.chats_list(limit=100)
                    чаты += клиент.chats_list(limit=100, offset=100)
                    пары += [
                        (з, каб)
                        for з in сторож.забытые(чаты, клиент.user_id, каб["название"])
                    ]
                finally:
                    клиент.close()

            # САМОЛЕЧЕНИЕ, а не только жалоба. 25.08 в 21:06 Николай написал
            # ровно в момент пересборки контейнера: старый уже снят, новый
            # поднялся в 21:07:21 — событие пропало. Сторож тогда честно
            # доложил «ждут ответа: 3» и на этом остановился: отвечать пришлось
            # вручную. Найденный ждущий чат прогоняется через тот же
            # разобрать(), что и живое событие: замок защищает от дублей,
            # решение (шаблон или агент) принимает штатная логика.
            for з, каб in пары[:10]:
                лог(з.chat_id, f"— сторож: ждёт {з.минут} мин, беру в разбор")
                await разобрать(з.chat_id, каб)

            текст = сторож.отчёт([з for з, _ in пары])
            if пары:
                print(f"[сторож] ждали ответа: {len(пары)}, взял в разбор", flush=True)
            else:
                print("[сторож] все отвечены", flush=True)
            # Сводку «клиент ждёт» Ирик получал каждый час по одному и тому же
            # человеку — 31.08 в чате трижды подряд висел один Музаффар, уже
            # закрытый как отказ. Разбор сторож делает сам, а факт ожидания
            # Ирику нужен один раз в дневном отчёте, а не в потоке дублей.
            if текст:
                в_отчёт("🔁 Сторож взял в разбор ждущих. " + текст)
        except Exception as ошибка:  # noqa: BLE001 — сторож не должен ронять вебхук
            print(f"[сторож] сбой: {type(ошибка).__name__}: {ошибка}", flush=True)

        await asyncio.sleep(ЧАС)


