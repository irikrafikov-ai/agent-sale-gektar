def битрикс_запрещает(имя: str) -> tuple[bool, str]:
    """Шаг 2.0 рабочего цикла: отказникам и дублям не пишем.

    Авито не знает, что человек уже отказался, — знает только Битрикс. Именно
    на этом 12.08 сломался разговор с Максом: сделка 2065 стояла ОТКАЗ, а в
    чате последнее слово было за клиентом, и текст напрашивался сам.

    Сопоставление по имени неточное, поэтому неоднозначность трактуется не в
    пользу отправки: вернём «запрещает» и отдадим чат агенту, у него есть чем
    разобраться. Лучше ответить через минуту, чем через секунду не тому.
    """
    имя = (имя or "").strip()
    if not имя:
        return True, "имя клиента не определилось"

    try:
        сделки = bitrix().crm_list(
            "deal",
            filter={"CATEGORY_ID": 0, "%TITLE": имя},
            select=["ID", "TITLE", "STAGE_ID"],
        )
    except Exception as ошибка:  # noqa: BLE001 — сеть Битрикса не должна ронять вебхук
        return True, f"Битрикс недоступен: {ошибка}"

    if not сделки:
        return False, "сделок нет — клиент новый"

    for сделка in сделки:
        название = (сделка.get("TITLE") or "").upper()
        стадия = сделка.get("STAGE_ID") or ""
        if "ОТКАЗ" in название or "ДУБЛЬ" in название or стадия.endswith("LOSE"):
            return True, f"сделка {сделка.get('ID')} — {сделка.get('TITLE')} / {стадия}"

    if len(сделки) > 1:
        return True, f"{len(сделки)} сделок по имени — неоднозначно"

    return False, f"сделка {сделки[0].get('ID')} активна"


def записать_в_битрикс(имя: str, chat_id: str) -> None:
    """Комментарий в таймлайн. Не смогли — не молчим, а говорим в Телеграм.

    Регламент: если действия нет в Битриксе, его не было. Префикс
    «📤 ОТПРАВЛЕНО» обязателен дословно — по нему контроль качества считает
    полноту таймлайна (код B05).
    """
    момент = datetime.now(МСК).strftime("%d.%m.%Y %H:%M")
    комментарий = (
        f"📤 ОТПРАВЛЕНО {момент} · Авито · чат {chat_id}\n"
        f"Первое касание. Повод: клиент открыл спецусловия (системный триггер Авито).\n\n"
        f"{ШАБЛОН}\n\n"
        f"Логика: отправлено вебхуком в первую минуту после триггера, без прогона — "
        f"клиент в этот момент в приложении. Текст фиксированный, по рабочему циклу, шаг 3.\n"
        f"Следующий шаг: ответит — квалификация; промолчит — цепочка касаний."
    )
    try:
        сделки = bitrix().crm_list(
            "deal",
            filter={"CATEGORY_ID": 0, "%TITLE": имя},
            select=["ID", "TITLE"],
        )
        if not сделки:
            telegram().send(
                f"⚠️ Шаблон ушёл в чат {chat_id} ({имя}), но сделки в Битриксе нет — "
                f"комментарий записать некуда. Нужна карточка."
            )
            return
        bitrix().timeline_comment_add(сделки[0]["ID"], комментарий)
        лог("битрикс: комментарий в сделку", сделки[0]["ID"])
    except Exception as ошибка:  # noqa: BLE001
        telegram().send(f"⚠️ Шаблон ушёл в чат {chat_id}, но комментарий не записался: {ошибка}")


