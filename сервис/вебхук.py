def найти_chat_id(данные: Any) -> str | None:
    """Достаёт chat_id из любой вложенности, не полагаясь на форму payload.

    Обход в ширину, а не рекурсия по известным ключам: если Авито переложит
    поле на уровень выше или ниже, вебхук продолжит работать.
    """
    очередь: deque[Any] = deque([данные])
    while очередь:
        узел = очередь.popleft()
        if isinstance(узел, dict):
            for ключ, значение in узел.items():
                if ключ in ("chat_id", "chatId") and isinstance(значение, str) and значение:
                    return значение
                очередь.append(значение)
        elif isinstance(узел, list):
            очередь.extend(узел)
    return None


def текст(сообщение: dict) -> str:
    содержимое = сообщение.get("content") or {}
    if isinstance(содержимое, dict):
        return str(содержимое.get("text") or "")
    return ""


def исходящее(сообщение: dict, наш_id: int) -> bool:
    """Наше сообщение или чужое.

    Основной признак — поле `direction`, оно есть в ответе API и не врёт.
    Сравнение author_id оставлено запасным: у системных сообщений Авито
    author_id равен 1, а не идентификатору клиента, и полагаться на него одного
    нельзя.
    """
    направление = сообщение.get("direction")
    if направление in ("out", "in"):
        return направление == "out"
    return str(сообщение.get("author_id")) == str(наш_id)


def темп_позволяет() -> bool:
    порог = time.time() - 3600
    while _отправки and _отправки[0] < порог:
        _отправки.popleft()
    return len(_отправки) < ПРЕДЕЛ_В_ЧАС


