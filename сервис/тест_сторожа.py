"""Сторож молчания: проверка на сценариях, которые уже случались.

    python сервис/тест_сторожа.py
"""

import sys
from datetime import datetime, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import сторож  # noqa: E402

НАШ = 84069402
КЛИЕНТ = 12345
СИСТЕМА = 1
СЕЙЧАС = datetime(2026, 8, 24, 15, 0, tzinfo=сторож.МСК)

провалов = 0


def проверь(что, факт, ждём):
    global провалов
    ок = факт == ждём
    провалов += not ок
    print(f"  {'✅' if ок else '❌'} {что}: {факт!r} (ждали {ждём!r})")


def чат(cid, автор, минут_назад, текст="", имя="Клиент"):
    return {
        "id": cid,
        "users": [{"id": НАШ, "name": "«Щекинские берега»"}, {"id": КЛИЕНТ, "name": имя}],
        "last_message": {
            "author_id": автор,
            "created": int((СЕЙЧАС - timedelta(minutes=минут_назад)).timestamp()),
            "content": {"text": текст},
            "type": "text",
        },
    }


print("1. Что считается забытым")
чаты = [
    чат("ответили", НАШ, 300, "наш ответ"),
    чат("свежее-порога", КЛИЕНТ, 5, "а свет есть?"),
    чат("ждёт-полчаса", КЛИЕНТ, 30, "а свет есть?", "Максим"),
    чат("ждёт-25-часов", КЛИЕНТ, 1500, "здравствуйте", "Ольга"),
    чат("системное-ждёт", СИСТЕМА, 90, "📞 Пользователь посмотрел номер", "Ангелина"),
]
з = сторож.забытые(чаты, НАШ, "gektar", СЕЙЧАС)
ид = [x.chat_id for x in з]
проверь("отвеченный не попал", "ответили" in ид, False)
проверь("свежий не попал", "свежее-порога" in ид, False)
проверь("ждущий полчаса попал", "ждёт-полчаса" in ид, True)
проверь("системный сигнал тоже попал", "системное-ждёт" in ид, True)
проверь("старше суток не попал — это база, а не срочность", "ждёт-25-часов" in ид, False)
проверь("всего забытых", len(з), 2)
проверь("сортировка — самый долгий первым", з[0].chat_id, "системное-ждёт")
проверь("имя клиента подтянулось", з[0].имя, "Ангелина")

print("\n2. Настоящий случай: Ангелина ждала 1 ч 34 мин")
ангелина = сторож.забытые([чат("ang", СИСТЕМА, 94, "📞 посмотрел номер", "Ангелина")], НАШ, "gektar", СЕЙЧАС)
проверь("поймана", len(ангелина), 1)
проверь("время посчитано", ангелина[0].минут, 94)
проверь("в строке часы, а не 94 минуты", "1 ч 34 мин" in ангелина[0].строка(), True)

print("\n2а. Настоящий случай 25.08: битая ссылка и вся база в алерте")
СИСТ_ТЕКСТ = ("Сообщение не поддерживается. Пожалуйста, перейдите в Авито мессенджер "
              "https://avito.ru/profile/messenger/channel/u2i-SlGuaH2PFbyPiEeKnLsCsg")
проверь("URL вырезан из цитаты", "http" in сторож._без_ссылок(СИСТ_ТЕКСТ), False)
проверь("смысл цитаты сохранён", "перейдите в Авито мессенджер" in сторож._без_ссылок(СИСТ_ТЕКСТ), True)
проверь("цитата не длиннее предела", len(сторож._без_ссылок(СИСТ_ТЕКСТ)) <= 110, True)
проверь("перевод строки не ломает вид", "\n" in сторож._без_ссылок("а\nб"), False)

анастасия = чат("u2i-SlGuaH2PFbyPiEeKnLsCsg", СИСТЕМА, 96 * 60 + 48, СИСТ_ТЕКСТ, "Анастасия")
проверь("ждущий 96 часов больше не попадает", len(сторож.забытые([анастасия], НАШ, "gektar", СЕЙЧАС)), 0)
свежий = сторож.забытые([чат("c", КЛИЕНТ, 40, "а свет есть?", "Пётр")], НАШ, "gektar", СЕЙЧАС)
проверь("ждущий 40 минут попадает", len(свежий), 1)
проверь("ссылка на чат собрана верно", свежий[0].ссылка,
        "https://www.avito.ru/profile/messenger/channel/c")
проверь("в строке нет чужих ссылок", "avito.ru/profile" in свежий[0].строка().split("«")[1], False)
граница = сторож.забытые([чат("d", КЛИЕНТ, 23 * 60, "?", "Иван")], НАШ, "gektar", СЕЙЧАС)
проверь("23 часа ещё попадает", len(граница), 1)

print("\n3. Тихие часы")
проверь("в 23:00 молчим", сторож.сейчас_тихо(СЕЙЧАС.replace(hour=23)), True)
проверь("в 03:00 молчим", сторож.сейчас_тихо(СЕЙЧАС.replace(hour=3)), True)
проверь("в 09:00 будим", сторож.сейчас_тихо(СЕЙЧАС.replace(hour=9)), False)
проверь("в 15:00 будим", сторож.сейчас_тихо(СЕЙЧАС.replace(hour=15)), False)
проверь("в 21:59 ещё будим", сторож.сейчас_тихо(СЕЙЧАС.replace(hour=21, minute=59)), False)

print("\n4. Отчёт")
проверь("пусто — молчим", сторож.отчёт([]), "")
один = сторож.отчёт(ангелина)
проверь("один клиент — единственное число", "Клиент ждёт ответа" in один, True)
проверь("chat_id в тексте", "ang" in один, True)
много = сторож.отчёт(сторож.забытые(чаты, НАШ, "gektar", СЕЙЧАС))
проверь("несколько — счётчик в шапке", "ждут ответа дольше" in много.lower(), True)
толпа = сторож.забытые([чат(f"c{i}", КЛИЕНТ, 60 + i, "?") for i in range(20)], НАШ, "gektar", СЕЙЧАС)
проверь("двадцать — подсказка про сбой", "похоже на сбой" in сторож.отчёт(толпа), True)

print("\n" + ("ВСЁ ЗЕЛЁНОЕ" if not провалов else f"ПРОВАЛОВ: {провалов}"))
sys.exit(1 if провалов else 0)
