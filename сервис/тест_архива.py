"""Архив ежедневных отчётов (Ирик, 21.09.2026) — без Битрикса."""

from __future__ import annotations

import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
for имя in ("интеграции", "интеграции.bitrix"):
    sys.modules.setdefault(имя, types.ModuleType(имя))
sys.modules["интеграции.bitrix"].Bitrix = object

import архив_отчётов as а  # noqa: E402

провалов = 0


def проверить(что, получили, ждали):
    global провалов
    ок = получили == ждали
    провалов += 0 if ок else 1
    print(f"  {'✅' if ок else '❌'} {что}: {получили!r} (ждали {ждали!r})")


отчёт = """# 📊 Отчёт за сутки — 20.09.2026
*Новых лидов:* 10

## ⚠️ Требуют вас
нет

## 📌 Вывод дня
### Что получилось
Ответ на конкретику.
### Завтра делаю иначе
1. Убираю закрытый вопрос.

#УРОК Расчёт без срока — тишина.

---
_прогон вечер_"""

з = а.разобрать(а.запись(отчёт, 1789919400))
проверить("запись читается обратно", (з["дата"], з["текст"] == отчёт.strip()), ("2026-09-20", True))
проверить("чужой комментарий — None", а.разобрать("📞 Звонок"), None)
проверить("эмодзи-коды Битрикса раскодируются",
          а.разобрать("ОТЧЁТ|1789919400|2026-09-20\n# :f09f938a: Отчёт\n## :f09f938c: Вывод дня\nтекст")["текст"],
          "# 📊 Отчёт\n## 📌 Вывод дня\nтекст")
в = а.вывод_из_отчёта(отчёт)
проверить("вывод дня вырезан от заголовка до разделителя", (в.startswith("## 📌 Вывод дня"), "#УРОК" in в, "_прогон" in в), (True, True, False))
проверить("нет вывода — пусто", а.вывод_из_отчёта("# Отчёт\nцифры"), "")

_архив = [{"когда": 2.0, "дата": "2026-09-20", "текст": отчёт}, {"когда": 1.0, "дата": "2026-09-19", "текст": "# без вывода"}]
а.прочитать = lambda дней=60: _архив
п = а.прошлые_выводы(2)
проверить("прошлые выводы — только дни, где вывод есть, с датой", (p := п.startswith("— 20.09 —\n## 📌 Вывод дня"), "19.09" in п), (True, False))
проверить("режется по пределу знаков", len(а.прошлые_выводы(2, предел_знаков=40).split("\n", 1)[1]) <= 40, True)

исходник = (Path(__file__).parent / "прогон.py").read_text()
проверить("вечерний отчёт уходит в архив после отправки", "архив_отчётов.сохранить(текст_отчёта)" in исходник, True)
проверить("вывод дня читает прошлые выводы", "архив_отчётов.прошлые_выводы(сколько=2)" in исходник, True)
проверить("дашборд отдаёт отчёты", '"отчёты": [' in (Path(__file__).parent / "дашборд_данные.py").read_text(), True)
проверить("раздел на странице", "Отчёты ежедневные" in (Path(__file__).parent / "дашборд.html").read_text(), True)

print(f"\n{'ВСЁ ЗЕЛЁНОЕ' if not провалов else f'ПРОВАЛОВ: {провалов}'}")
sys.exit(1 if провалов else 0)
