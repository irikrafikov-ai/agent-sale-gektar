"""Управление подпиской на вебхук Авито.

Осторожность здесь не лишняя: на аккаунте уже висит чужая подписка —
`tools.reyting.pro`, сторонний сервис. Судя по всему, именно через неё в
Битрикс приходят обращения и открытая линия заводит сделки. Публично Авито не
пишет, добавляет ли подписка новый адрес или заменяет единственный. Если
заменяет, а мы этого не заметим, сделки перестанут создаваться молча — и
обнаружится это через сутки по пустой воронке.

Поэтому порядок такой: снимок до → подписка → снимок после → сверка. Если
чужой адрес пропал, скрипт возвращает его на место сам и говорит об этом
громко. Окно в пару секунд остаётся, но это несопоставимо с молчаливой
поломкой на сутки.

Команды:
    python сервис/подписка.py список [кабинет]
    python сервис/подписка.py подписать https://<домен>/avito/<секрет> [кабинет]
    python сервис/подписка.py отписать https://<домен>/avito/<секрет> [кабинет]

Кабинет — ключ из кабинеты.py (gektar, dolina). Без него берутся «Берега».
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from интеграции.avito import Avito  # noqa: E402

import кабинеты as реестр  # noqa: E402

СПИСОК = "/messenger/v1/subscriptions"
ПОДПИСАТЬ = "/messenger/v3/webhook"
ОТПИСАТЬ = "/messenger/v1/webhook/unsubscribe"


def подписки(клиент: Avito) -> list[dict]:
    ответ = клиент._request("POST", СПИСОК)
    return (ответ or {}).get("subscriptions", [])


def показать(подписки_: list[dict]) -> None:
    if not подписки_:
        print("  (пусто)")
        return
    for п in подписки_:
        print(f"  · {п.get('url')}   (версия {п.get('version')})")


def команда_список(клиент: Avito) -> None:
    print("Активные подписки:")
    показать(подписки(клиент))


def команда_подписать(клиент: Avito, url: str) -> int:
    до = подписки(клиент)
    print("Было:")
    показать(до)

    адреса_до = {п.get("url") for п in до}
    if url in адреса_до:
        print(f"\n✅ Этот адрес уже подписан, ничего не меняю: {url}")
        return 0

    print(f"\nПодписываю: {url}")
    клиент._request("POST", ПОДПИСАТЬ, json={"url": url})

    после = подписки(клиент)
    print("Стало:")
    показать(после)

    адреса_после = {п.get("url") for п in после}

    if url not in адреса_после:
        print("\n❌ Наш адрес в списке не появился. Подписка не состоялась.")
        return 1

    пропали = адреса_до - адреса_после
    if пропали:
        print("\n🚨 ПОДПИСКА ОКАЗАЛАСЬ ЗАМЕНЯЮЩЕЙ. Исчезли чужие адреса:")
        for адрес in пропали:
            print(f"   · {адрес}")
        print("\nВозвращаю их на место...")
        for адрес in пропали:
            try:
                клиент._request("POST", ПОДПИСАТЬ, json={"url": адрес})
                print(f"   ✅ вернул {адрес}")
            except Exception as ошибка:  # noqa: BLE001
                print(f"   ❌ НЕ вернул {адрес}: {ошибка}")
        итог = подписки(клиент)
        print("\nИтог:")
        показать(итог)
        print(
            "\n⚠️ Авито держит только одну подписку. Наш вебхук и чужой сервис "
            "одновременно работать не смогут — нужно решение Ирика: либо принимать "
            "события у себя и пересылать их дальше, либо отказаться от одного из двух."
        )
        return 2

    print("\n✅ Готово. Чужие подписки на месте, наша добавилась.")
    return 0


def команда_отписать(клиент: Avito, url: str) -> int:
    print(f"Отписываю: {url}")
    клиент._request("POST", ОТПИСАТЬ, json={"url": url})
    print("Стало:")
    показать(подписки(клиент))
    return 0


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 1

    команда = sys.argv[1]

    # Кабинет — последний аргумент, если он есть в реестре. Без него берётся
    # «Берега»: так прежние команды продолжают работать без правок.
    ключ = реестр.ПО_УМОЛЧАНИЮ
    аргументы = sys.argv[2:]
    if аргументы and аргументы[-1] in реестр.КАБИНЕТЫ:
        ключ = аргументы.pop()
    каб = реестр.кабинет(ключ)

    if not реестр.настроен(каб):
        print(
            f"Кабинет «{каб['название']}» не настроен: задайте "
            + " и ".join(каб["переменные"])
        )
        return 1

    id_, secret = каб["переменные"]
    клиент = Avito(client_id=os.environ[id_], client_secret=os.environ[secret])
    print(f"Кабинет: {каб['название']} (Авито id {каб['avito_user_id']})\n")

    if команда == "список":
        команда_список(клиент)
        return 0

    if команда in ("подписать", "отписать"):
        if not аргументы:
            print(f"Нужен URL: python сервис/подписка.py {команда} https://... [кабинет]")
            return 1
        url = аргументы[0]
        if not url.startswith("https://"):
            print("Авито принимает только https.")
            return 1
        return (команда_подписать if команда == "подписать" else команда_отписать)(клиент, url)

    print(f"Неизвестная команда: {команда}")
    print(__doc__)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
