"""Правила, общие для вебхука и инструментов агента.

Живут отдельно намеренно: вебхук и инструменты нужны обоим, но инструменты
тянут за собой Claude Agent SDK, а вебхук должен подниматься без него.
06.09 импорт инструментов в вебхук уронил тесты именно по этой причине.

Дублировать эти проверки в двух файлах нельзя: они разъедутся, и один из
путей отправки останется без защиты. Шаблон уходит через вебхук напрямую,
живые сообщения — через инструменты; правило должно быть буквально одним.
"""

from __future__ import annotations


def служебное_авито(сообщение: dict) -> bool:
    """Уведомление площадки, а не реплика человека.

    Правило Ирика 03.09.2026: служебные сообщения Авито НИКОГДА не считаются
    общением с клиентом — ни за входящее, ни за исходящее. Они технические.
    """
    if сообщение.get("type") == "system":
        return True
    return str(сообщение.get("author_id")) in ("0", "1")


# Просьба не писать. Правило Ирика 06.09.2026: попросил — молчим навсегда.
# Анна просила ДВАЖДЫ, и оба раза ей писали снова. Второе такое сообщение —
# это уже не «не интересно», а раздражение, и следом идёт жалоба площадке.
#
# Дополнено 07.09.2026: сюда же — прямой отказ от предложения, не только
# дословное «не пишите». Андрей Гореликов 12.08 получил пометку НЕ ПИСАТЬ
# (карточка 2087), но она стояла без привязки к чату и не сработала — после
# ннего ушло ещё четыре сообщения, и 06.09 он ответил «Не нужно больше
# информации!». Операционно это то же самое действие, что и «не пишите»:
# молчим навсегда, закрываем карточку. Разделять их не за чем — оба ведут
# в один и тот же стоп-кран и одну и ту же ревизию.
# ЖЁСТКИЕ формулировки: человек просит прекратить общение. Действуют
# навсегда и независимо от того, что он писал после.
ПРОСЬБА_НЕ_ПИСАТЬ_ЖЁСТКО = (
    "не пишите", "не писать", "не пиши", "можете мне не писать",
    "не беспокойте", "не беспокоить", "прекратите писать", "перестаньте писать",
    "отпишитесь", "отписаться", "удалите мой номер", "больше не пишите",
    "хватит писать", "не надо мне писать", "не нужно мне писать",
    "уберите меня", "исключите меня", "я не нуждаюсь", "спам",
    "не нужно больше информации",
)

# МЯГКИЕ: отказ от ПРЕДЛОЖЕНИЯ, а не от разговора. Считаются стоп-краном
# только если человек после них замолчал.
#
# 28.09.2026: клиент написал «Не банк? … Не банки мне не интересно» — это
# возражение против банковской рассрочки, сказанное посреди разговора.
# Стоп-кран прочитал «не интересно» как «не пишите», ответ не ушёл, а
# человек задал после этого ещё восемь вопросов. Горящий клиент остался в
# тишине, и по предписанию крана его следовало ещё и закрыть с пометкой
# «НЕ ПИСАТЬ». Тот, кто просит молчать, не задаёт потом восемь вопросов —
# поэтому дальнейшие его реплики отменяют мягкий отказ.
ПРОСЬБА_НЕ_ПИСАТЬ_МЯГКО = (
    "не интересно", "неинтересно", "больше не нужно",
    "не буду покупать", "не буду брать",
)

# Совместимость: прежнее имя осталось полным списком — им пользуются
# подсказки агенту и тесты.
ПРОСЬБА_НЕ_ПИСАТЬ = ПРОСЬБА_НЕ_ПИСАТЬ_ЖЁСТКО + ПРОСЬБА_НЕ_ПИСАТЬ_МЯГКО


def жёсткий_запрет(сообщение: dict) -> bool:
    """Только явная просьба прекратить общение переносится на все чаты."""
    текст = ((сообщение.get("content") or {}).get("text") or "").lower()
    return any(ф in текст for ф in ПРОСЬБА_НЕ_ПИСАТЬ_ЖЁСТКО)


def просил_не_писать(сообщения: list[dict], наш_id) -> dict | None:
    """Реплика клиента с просьбой больше не писать — если она была.

    Ищем во ВСЕЙ переданной истории, а не только в последнем сообщении:
    просьба не перестаёт действовать оттого, что человек потом молчал.

    Мягкий отказ («не интересно») отменяется, если после него клиент писал
    ещё: разговор продолжился, значит это было возражение по существу, а не
    просьба замолчать.
    """
    его = []
    for м in сообщения or []:
        if служебное_авито(м):
            continue
        if str(м.get("author_id")) == str(наш_id) or м.get("direction") == "out":
            continue
        его.append(м)

    # История приходит и новыми вперёд, и старыми вперёд — упорядочим сами.
    его.sort(key=lambda м: м.get("created") or 0)

    for номер, м in enumerate(его):
        текст = ((м.get("content") or {}).get("text") or "").lower()
        if any(ф in текст for ф in ПРОСЬБА_НЕ_ПИСАТЬ_ЖЁСТКО):
            return м
        if any(ф in текст for ф in ПРОСЬБА_НЕ_ПИСАТЬ_МЯГКО) and номер == len(его) - 1:
            return м
    return None
