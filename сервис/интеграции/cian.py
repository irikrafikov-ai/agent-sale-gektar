"""Выгрузка участков на ЦИАН: слой данных.

ЦИАН забирает XML-фид по ссылке сам, раз в 1–6 часов. Наша задача — отдавать
по адресу актуальный срез шахматки: проданное и забронированное исчезает из
объявлений само, цены не расходятся с тем, что видит клиент в туре.

Теги и допустимые значения взяты из официальных техтребований Циан
(cian.ru/xml_import/doc, формат «Циан 2.0», категория landSale), прочитанных
через браузер: обычным HTTP-запросом сайт отдаёт капчу Яндекса.
"""

from __future__ import annotations

import csv
import io
from dataclasses import dataclass
from typing import Iterable
from xml.sax.saxutils import escape

import httpx

# Живая шахматка — тот же источник, что красит участки в 3D-туре.
ШАХМАТКА = (
    "https://docs.google.com/spreadsheets/d/"
    "1JhlaNnwKEQY1OUQnsCMrCDPk3ADooXMdaCm8Hzb87uM/gviz/tq?tqx=out:csv"
)

# Что выгружаем на площадку. «Забронирован» не выгружаем: бронь снимает
# участок с продажи, а объявление на забронированный участок собирает звонки,
# на которые нечем ответить.
ПРОДАЁМ = {"свободен", "акция"}

# Посёлок. Координаты — точка въезда, та же, что уходит клиентам в чат.
АДРЕС = "Тульская область, Щёкинский район, с. Костомарово"
ШИРОТА, ДОЛГОТА = 53.923446, 37.623176
КАДАСТРОВЫЙ_КВАРТАЛ = "71:22:050309"
ПОСЁЛОК = "Щекинские берега"
ТУР = "https://partners.gektar.expert/tour/kostomarovo/"

# ВРИ и категория земель — по базе знаний: ЛПХ в границах населённого пункта,
# дом и прописка возможны. Значения из справочника Циан.
ВРИ = "privateFarm"              # Личное подсобное хозяйство
КАТЕГОРИЯ_ЗЕМЕЛЬ = "settlements"  # Земли населённых пунктов

# Телефон объявлений — подтверждённый основной номер кабинета ЦИАН.
# Обязательное поле: без телефона объявление не публикуется.
# Циан подменяет реальный номер в объявлении, это их защита от спама.
ТЕЛЕФОН = ("+7", "9628883311")

# ⚠️ КАКИЕ УЧАСТКИ ПУБЛИКУЕМ НА ЦИАН — РЕШАЕТ ТОЛЬКО ИРИК.
#
# Пустой список означает «ничего не публиковать», и это намеренное значение по
# умолчанию, а не заглушка. Фид, в котором лежит вся шахматка, публикует все
# участки разом в ту минуту, когда ссылку вставят в кабинет: это не постепенный
# выход на площадку, а одно необратимое движение — 32 объявления, деньги за
# размещение и поток звонков, к которому никто не готовился.
#
# Указание Ирика 24.08.2026: «не надо 32 объявления, я сам скажу, что нужно
# опубликовать». Номера добавляются сюда по его слову, по одному или пачкой.
#
# Проданные и забронированные из шахматки отсеиваются и так — этот список
# сужает дальше, до того, что решено показывать.
К_ПУБЛИКАЦИИ: tuple[str, ...] = ()


@dataclass(frozen=True)
class Участок:
    номер: str
    площадь_соток: float
    цена_рассрочка: int          # цена из шахматки, она же цена рассрочки 0%
    цена_сразу: int              # при полной оплате
    по_акции: bool

    @property
    def внешний_id(self) -> str:
        """Стабильный идентификатор объявления. Меняться не должен никогда:
        по нему площадка отличает обновление от нового объявления."""
        return f"schekinskie-berega-{self.номер}"


def _число(текст: str) -> float | None:
    текст = (текст or "").strip().replace("\xa0", "").replace(" ", "").replace(",", ".")
    try:
        return float(текст)
    except ValueError:
        return None


def разобрать(csv_текст: str) -> list[Участок]:
    """Шахматка → список участков, годных к выгрузке.

    Строки без номера, площади или цены пропускаем молча: в шахматке есть
    служебные и пустые строки, и падать на них нельзя — фид должен отдаваться
    даже когда таблицу правят руками.
    """
    строки = list(csv.reader(io.StringIO(csv_текст)))
    участки: list[Участок] = []

    for строка in строки[1:]:
        if len(строка) < 4:
            continue
        номер = (строка[0] or "").strip().lstrip("№")
        статус = (строка[1] or "").strip().lower()
        if not номер or статус not in ПРОДАЁМ:
            continue

        площадь = _число(строка[2])
        цена = _число(строка[3])
        if not площадь or not цена:
            continue

        участки.append(
            Участок(
                номер=номер,
                площадь_соток=площадь,
                цена_рассрочка=int(цена),
                # Скидка при полной оплате — 10%, как в чатах и в объявлениях.
                цена_сразу=int(round(цена * 0.9)),
                по_акции=(статус == "акция"),
            )
        )
    return участки


def загрузить(таймаут: float = 20.0) -> list[Участок]:
    ответ = httpx.get(ШАХМАТКА, timeout=таймаут, follow_redirects=True)
    ответ.raise_for_status()
    return разобрать(ответ.text)


# --- рендер фида ---------------------------------------------------------
#
# Ограничения Циан на текст описания, из техтребований:
#   · длина 15–7000 символов;
#   · символ & ЗАПРЕЩЁН — не экранируется, а запрещён, поэтому вырезаем;
#   · символы № / \\ будут удалены площадкой — убираем сами, чтобы текст в
#     объявлении читался так же, как мы его написали, а не с дырами.

ЗАПРЕЩЕНО_В_ОПИСАНИИ = "&№/\\"


def _чистый_текст(текст: str) -> str:
    for символ in ЗАПРЕЩЕНО_В_ОПИСАНИИ:
        текст = текст.replace(символ, "")
    return escape(текст).strip()


def описание(у: Участок) -> str:
    акция = (
        f"\nСейчас участок идёт по акции: {у.цена_сразу:,} руб при полной оплате.".replace(",", " ")
        if у.по_акции
        else f"\nПри полной оплате цена {у.цена_сразу:,} руб.".replace(",", " ")
    )
    return _чистый_текст(
        f"Участок {у.номер} площадью {у.площадь_соток} сотки в посёлке {ПОСЁЛОК}, "
        f"село Костомарово Щёкинского района Тульской области.\n\n"
        "Земли населённых пунктов, ЛПХ: можно построить жилой дом и прописаться, "
        "а также держать хозяйство, поставить теплицы и хозпостройки.\n\n"
        "Посёлок стоит у водохранилища. До города Советск 1-2 км пешком: школа, "
        "два детских сада, больница, магазины. До городского пляжа 450 метров.\n\n"
        "Участки размежёваны, у каждого свой кадастровый номер, границы внесены "
        "в ЕГРН. Территория идёт мягким уклоном к воде, за счёт этого дома не "
        "закрывают друг другу вид.\n\n"
        f"Цена {у.цена_рассрочка:,} руб. Рассрочка 0 процентов на 12 месяцев без "
        "банков и одобрений.".replace(",", " ") + акция + "\n\n"
        "Продаём напрямую от собственника, без комиссий и посредников. "
        "Оформление через Сбербанк: деньги продавец получает только после того, "
        "как участок переоформлен на покупателя. Можно дистанционно."
    )


def объект(у: Участок, телефон: tuple[str, str], фото: list[str]) -> str:
    код, номер = телефон
    фото_xml = "".join(
        f"<PhotoSchema><FullUrl>{escape(u)}</FullUrl>"
        f"<IsDefault>{'true' if i == 0 else 'false'}</IsDefault></PhotoSchema>"
        for i, u in enumerate(фото)
    )
    return (
        "<object>"
        "<Category>landSale</Category>"
        f"<ExternalId>{у.внешний_id}</ExternalId>"
        f"<Description>{описание(у)}</Description>"
        f"<Address>{escape(АДРЕС)}</Address>"
        f"<Coordinates><Lat>{ШИРОТА}</Lat><Lng>{ДОЛГОТА}</Lng></Coordinates>"
        f"<SettlementName>{escape(ПОСЁЛОК)}</SettlementName>"
        f"<Phones><PhoneSchema><CountryCode>{escape(код)}</CountryCode>"
        f"<Number>{escape(номер)}</Number></PhoneSchema></Phones>"
        "<Land>"
        f"<Area>{у.площадь_соток}</Area>"
        "<AreaUnitType>sotka</AreaUnitType>"
        f"<PermittedLandUseType>{ВРИ}</PermittedLandUseType>"
        f"<LandCategory>{КАТЕГОРИЯ_ЗЕМЕЛЬ}</LandCategory>"
        "</Land>"
        "<HasElectricity>true</HasElectricity>"
        f"<ObjectTour><FullUrl>{escape(ТУР)}</FullUrl></ObjectTour>"
        + (f"<Photos>{фото_xml}</Photos>" if фото else "")
        + "<BargainTerms>"
        f"<Price>{у.цена_рассрочка}</Price>"
        "<Currency>rur</Currency>"
        "</BargainTerms>"
        "</object>"
    )


def к_публикации(участки: Iterable[Участок]) -> list[Участок]:
    """Оставляет только то, что Ирик разрешил публиковать. Пусто — значит пусто."""
    разрешено = set(К_ПУБЛИКАЦИИ)
    return [у for у in участки if у.номер in разрешено]


def фид(
    участки: Iterable[Участок],
    телефон: tuple[str, str] = ТЕЛЕФОН,
    фото: list[str] | None = None,
    только_разрешённые: bool = True,
) -> str:
    """Готовый XML для выгрузки. Телефон обязателен: без него Циан не публикует.

    По умолчанию в фид попадают ТОЛЬКО участки из К_ПУБЛИКАЦИИ. Отключать этот
    отбор осмысленно лишь в тестах: в проде пустой фид — правильное поведение,
    а не поломка.
    """
    отобранные = к_публикации(участки) if только_разрешённые else list(участки)
    тела = "".join(объект(у, телефон, фото or []) for у in отобранные)
    return (
        '<?xml version="1.0" encoding="UTF-8"?>'
        "<feed><feed_version>2</feed_version>" + тела + "</feed>"
    )


def сводка(участки: Iterable[Участок]) -> str:
    участки = list(участки)
    акция = sum(1 for у in участки if у.по_акции)
    return f"к выгрузке {len(участки)} участков, из них по акции {акция}"
