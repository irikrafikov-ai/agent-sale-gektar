"""Цифры ежедневного отчёта — считает КОД, а не модель.

Форма утверждена Ириком 09.09.2026. Один сводный отчёт по обоим кабинетам,
раз в сутки, вечерним прогоном.

Почему цифры здесь, а не в голове агента. Тот же урок, что и с молчунами
01.09: три прохода моделью дали три разных числа, потому что служебные
уведомления Авито считались за общение, а живые ответы терялись. Отчёт
проверяется агентом контроля качества (код O01), и расхождение цифры с
фактом там тяжелее почти любого другого нарушения. Значит цифра обязана
быть воспроизводимой: один и тот же период даёт один и тот же ответ.

Почему это ещё и чинит ежедневность. Раньше вечерний прогон собирал день,
читая журнал утреннего. Журнал лежит внутри контейнера и стирается при
каждом передеплое, а деплоев бывает 3–4 в сутки — «отчёт за день» регулярно
оказывался отчётом за полдня, и заметить это было нельзя. Здесь источник
другой: Авито и Битрикс, оба переживают любой деплой.

Период — скользящие сутки: от 18:30 вчера до 18:30 сегодня. Вечерняя
активность клиентов (телефон в 23:30 — реальный случай 08.09) не теряется,
а попадает в отчёт следующего дня.
"""

from __future__ import annotations

import os
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

sys_path = str(Path(__file__).parent)
import sys  # noqa: E402

if sys_path not in sys.path:
    sys.path.insert(0, sys_path)

from интеграции.avito import Avito  # noqa: E402
from интеграции.bitrix import Bitrix  # noqa: E402

import кабинеты as реестр  # noqa: E402
from правила import служебное_авито  # noqa: E402
import расход as учёт_расхода  # noqa: E402

МСК = timezone(timedelta(hours=3))

# Пауза между чатами: сплошной проход по мессенджеру Авито упирался в 503.
ПАУЗА = float(os.environ.get("ПАУЗА_ОТЧЁТ", "0.15"))

# Стадии, попадание в которые означает «клиент стал тёплым».
# Тёплый — это живой человек с телефоном и следующим шагом, а не просто
# открытый диалог. В воронке это ровно три стадии.
СТАДИИ_ТЁПЛЫХ = ("UC_CONTACT", "UC_CALL_DONE", "UC_MEET_SET")

# Стадии, которые считаются движением вперёд (клиент «заинтересовался»).
# NEW и LOSE сюда не входят: первое — точка старта, второе — выход из воронки.
СТАДИИ_ВПЕРЁД = ("EXECUTING", "PREPARATION", *СТАДИИ_ТЁПЛЫХ, "FINAL_INVOICE", "WON")


def окно(конец: datetime | None = None, часов: int = 24) -> tuple[float, float]:
    """Скользящие сутки: (начало, конец) в unix-секундах."""
    конец = конец or datetime.now(МСК)
    return (конец - timedelta(hours=часов)).timestamp(), конец.timestamp()


def _в_окне(метка: Any, начало: float, конец: float) -> bool:
    try:
        м = float(метка or 0)
    except (TypeError, ValueError):
        return False
    return начало <= м <= конец


def диалоги_кабинета(ключ: str, начало: float, конец: float) -> dict:
    """Диалоги, наши сообщения и отклики клиентов за период по одному кабинету.

    Историю читаем ТОЛЬКО у чатов, тронутых за период (поле `updated`), —
    иначе это 300+ запросов вместо 30, а лимиты Авито уже давали 503.
    """
    каб = реестр.кабинет(ключ)
    пусто = {"диалогов": 0, "с_ответом": 0, "отправлено": 0, "кабинет": каб["название"]}
    if not реестр.настроен(каб):
        return пусто

    id_, secret = каб["переменные"]
    клиент = Avito(client_id=os.environ[id_], client_secret=os.environ[secret])
    try:
        наш_id = клиент.user_id
        чаты: list[dict] = []
        сдвиг = 0
        while True:
            порция = клиент.chats_list(limit=100, offset=сдвиг)
            чаты.extend(порция)
            if len(порция) < 100:
                break
            сдвиг += 100

        живые = [ч for ч in чаты if _в_окне(ч.get("updated"), начало, конец)]
        отправлено = 0
        с_ответом = 0

        for чат in живые:
            chat_id = чат.get("id")
            if not chat_id:
                continue
            time.sleep(ПАУЗА)
            try:
                сообщения = клиент.chat_messages(chat_id, limit=100)
            except Exception:  # noqa: BLE001 — один чат не роняет отчёт
                continue

            наши_в_окне = 0
            ответил = False
            for м in сообщения:
                if служебное_авито(м) or not _в_окне(м.get("created"), начало, конец):
                    continue
                наше = str(м.get("author_id")) == str(наш_id) or м.get("direction") == "out"
                if наше:
                    наши_в_окне += 1
                else:
                    ответил = True
            отправлено += наши_в_окне
            с_ответом += 1 if ответил else 0

        return {
            "диалогов": len(живые),
            "с_ответом": с_ответом,
            "отправлено": отправлено,
            "кабинет": каб["название"],
        }
    finally:
        клиент.close()


def _битрикс_срез(b: Bitrix, начало: float, конец: float) -> dict:
    """Заинтересовались, отказали и НОВЫЕ тёплые — из Битрикса.

    «Новые тёплые» считаются по MOVED_TIME: человек попадает в счётчик один
    раз, в тот день, когда впервые дошёл до стадии с телефоном и следующим
    шагом (указание Ирика 09.09.2026 — считать только уникальных). Кто был
    тёплым вчера и остаётся тёплым сегодня, в счётчик не идёт, но и не
    пропадает — он уходит в строку «ранее тёплые, ещё в работе».
    """
    с = datetime.fromtimestamp(начало, МСК).strftime("%Y-%m-%dT%H:%M:%S")
    по = datetime.fromtimestamp(конец, МСК).strftime("%Y-%m-%dT%H:%M:%S")

    двигались = b.crm_list(
        "deal",
        filter={"CATEGORY_ID": 0, ">=MOVED_TIME": с, "<=MOVED_TIME": по},
        select=["ID", "TITLE", "STAGE_ID", "UF_CRM_FAIL_REASON", "MOVED_TIME"],
        limit=500,
    )

    вперёд = [д for д in двигались if (д.get("STAGE_ID") or "") in СТАДИИ_ВПЕРЁД]
    отказы = [д for д in двигались if (д.get("STAGE_ID") or "").endswith("LOSE")]
    новые_тёплые = [д for д in двигались if (д.get("STAGE_ID") or "") in СТАДИИ_ТЁПЛЫХ]

    # Тёплые, ставшие тёплыми РАНЬШЕ и всё ещё в работе — чтобы пайплайн не
    # исчезал из виду, когда счётчик показывает только новых.
    все_тёплые = b.crm_list(
        "deal",
        filter={"CATEGORY_ID": 0, "STAGE_ID": list(СТАДИИ_ТЁПЛЫХ)},
        select=["ID", "TITLE", "STAGE_ID", "MOVED_TIME"],
        limit=500,
    )
    новые_ид = {д.get("ID") for д in новые_тёплые}
    ранее = [д for д in все_тёплые if д.get("ID") not in новые_ид]

    причины: dict[str, int] = {}
    for д in отказы:
        код = str(д.get("UF_CRM_FAIL_REASON") or "не указана")
        причины[код] = причины.get(код, 0) + 1

    return {
        "заинтересовались": len(вперёд),
        "отказали": len(отказы),
        "причины": причины,
        "новые_тёплые": новые_тёплые,
        "ранее_тёплые": ранее,
    }


# Человеческие названия причин отказа — коды в отчёте бесполезны.
ПРИЧИНЫ = {
    "55": "не отвечает",
    "59": "не интересно",
    "61": "купил в другом месте",
    "63": "локация",
    "65": "нецелевой",
    "93": "дубль",
    "95": "не выяснена",
}


def собрать(конец: datetime | None = None) -> dict:
    """Все цифры отчёта за скользящие сутки, по обоим кабинетам сразу."""
    начало, кон = окно(конец)
    по_кабинетам = [диалоги_кабинета(к, начало, кон) for к in реестр.КАБИНЕТЫ]

    b = Bitrix()
    try:
        срез = _битрикс_срез(b, начало, кон)
    finally:
        b.close()

    # Расход на токены за те же сутки — требование Ирика 09.09.2026.
    # Журнал общий для всех пяти контейнеров агента, лежит в Битриксе.
    try:
        деньги = учёт_расхода.за_период(начало, кон)
    except Exception as ошибка:  # noqa: BLE001 — отчёт дороже одной строки
        print(f"[расход] не собрался: {type(ошибка).__name__}: {ошибка}")
        деньги = {"usd": 0.0, "запусков": 0, "по_моделям": {}, "по_видам": {}}

    return {
        "начало": datetime.fromtimestamp(начало, МСК),
        "конец": datetime.fromtimestamp(кон, МСК),
        "расход": деньги,
        "диалогов": sum(к["диалогов"] for к in по_кабинетам),
        "с_ответом": sum(к["с_ответом"] for к in по_кабинетам),
        "отправлено": sum(к["отправлено"] for к in по_кабинетам),
        "по_кабинетам": по_кабинетам,
        **срез,
    }


def шапка(данные: dict) -> str:
    """Верхний блок отчёта — форма утверждена Ириком 09.09.2026."""
    причины = " · ".join(
        f"{ПРИЧИНЫ.get(к, к)} {n}" for к, n in sorted(данные["причины"].items(), key=lambda x: -x[1])
    )
    разбивка = " · ".join(
        f"{к['кабинет']} {к['диалогов']}" for к in данные["по_кабинетам"] if к["диалогов"]
    )

    строки = [
        f"# 📊 Отчёт за сутки — {данные['конец']:%d.%m.%Y}, {данные['конец']:%H:%M} "
        f"(с {данные['начало']:%d.%m} {данные['начало']:%H:%M})",
        "",
        f"*Диалогов:* {данные['диалогов']} (клиент ответил в {данные['с_ответом']})"
        + (f" — {разбивка}" if разбивка else ""),
        f"*Сообщений отправлено:* {данные['отправлено']}",
        f"*Заинтересовались:* {данные['заинтересовались']} — продвинулись по стадии",
        f"*Отказали:* {данные['отказали']}" + (f" ({причины})" if причины else ""),
        f"*Новых тёплых:* {len(данные['новые_тёплые'])}",
        учёт_расхода.словами(данные.get("расход") or {}),
    ]

    if данные["новые_тёплые"]:
        строки += ["", f"## 🔥 Новые тёплые — {len(данные['новые_тёплые'])}"]
        строки += [f"- {д.get('TITLE')} (сделка {д.get('ID')})" for д in данные["новые_тёплые"][:10]]

    if данные["ранее_тёплые"]:
        имена = " · ".join(
            (д.get("TITLE") or "").split("(")[0].strip() for д in данные["ранее_тёплые"][:8]
        )
        строки += ["", f"Ранее тёплые, ещё в работе — {len(данные['ранее_тёплые'])}: {имена}"]

    return "\n".join(строки)


def main() -> int:
    """python сервис/отчёт.py — посчитать и показать цифры, ничего не отправляя."""
    данные = собрать()
    print(шапка(данные))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
