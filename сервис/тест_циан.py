"""Проверка слоя данных выгрузки на ЦИАН — на живой шахматке и на подставной.

Живая часть важнее подставной: шахматку правят руками, и фид должен
переживать пустые строки, запятые в числах и неожиданные статусы.

    python сервис/тест_циан.py
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from интеграции import cian  # noqa: E402

провалов = 0


def проверь(что, факт, ждём):
    global провалов
    ок = факт == ждём
    провалов += not ок
    print(f"  {'✅' if ок else '❌'} {что}: {факт!r} (ждали {ждём!r})")


print("1. Разбор подставной шахматки")
ПОДСТАВНАЯ = """Участок,Статус,Площадь,Цена,Цена за сотку
1,Продан,10,,
2,Свободен,"8,67",390150,45
3,Акция,"7,91",295043,37
,,,,
99,Забронирован,8,360000,45
4,Свободен,мусор,295596,37
5,Свободен,"7,7",,
"""
у = cian.разобрать(ПОДСТАВНАЯ)
проверь("проданные не выгружаются", "1" in [x.номер for x in у], False)
проверь("забронированные не выгружаются", "99" in [x.номер for x in у], False)
проверь("пустая строка не роняет разбор", len(у), 2)
проверь("акция помечена", [x.номер for x in у if x.по_акции], ["3"])
проверь("запятая в площади разобрана", у[0].площадь_соток, 8.67)
проверь("скидка 10% посчитана", у[0].цена_сразу, 351135)
проверь("битая площадь пропущена", "4" in [x.номер for x in у], False)
проверь("цена без значения пропущена", "5" in [x.номер for x in у], False)
проверь("внешний id стабилен", у[0].внешний_id, "schekinskie-berega-2")

print("\n2. Живая шахматка")
try:
    живые = cian.загрузить()
except Exception as ошибка:  # noqa: BLE001
    print(f"  ⚠️ шахматка недоступна ({ошибка}) — живую часть пропускаю")
else:
    print(f"  · {cian.сводка(живые)}")
    проверь("участки нашлись", len(живые) > 0, True)
    проверь("у всех положительная площадь", all(x.площадь_соток > 0 for x in живые), True)
    проверь("у всех положительная цена", all(x.цена_рассрочка > 0 for x in живые), True)
    проверь("цена сразу меньше рассрочки", all(x.цена_сразу < x.цена_рассрочка for x in живые), True)
    проверь("номера уникальны", len({x.номер for x in живые}), len(живые))
    проверь("id уникальны", len({x.внешний_id for x in живые}), len(живые))

print("\n3. Фид: структура и ограничения Циан")
из_живой = cian.загрузить() if "живые" in dir() else []
у = cian.разобрать(ПОДСТАВНАЯ)
xml = cian.фид(у, только_разрешённые=False)
import xml.etree.ElementTree as ET
корень = ET.fromstring(xml)
проверь("корень feed", корень.tag, "feed")
проверь("версия 2", корень.findtext("feed_version"), "2")
проверь("объектов столько же, сколько участков", len(корень.findall("object")), len(у))
о = корень.find("object")
проверь("категория landSale", о.findtext("Category"), "landSale")
проверь("единица площади — сотка", о.findtext("Land/AreaUnitType"), "sotka")
проверь("ВРИ — ЛПХ", о.findtext("Land/PermittedLandUseType"), "privateFarm")
проверь("категория земель", о.findtext("Land/LandCategory"), "settlements")
проверь("валюта рубль", о.findtext("BargainTerms/Currency"), "rur")
проверь("цена = цене рассрочки", о.findtext("BargainTerms/Price"), str(у[0].цена_рассрочка))
проверь("телефон из кабинета ЦИАН", о.findtext("Phones/PhoneSchema/Number"), "9628883311")
проверь("код страны", о.findtext("Phones/PhoneSchema/CountryCode"), "+7")
проверь("3D-тур передан", о.findtext("ObjectTour/FullUrl"), cian.ТУР)

оп = о.findtext("Description")
проверь("описание не короче 15 символов", len(оп) >= 15, True)
проверь("описание не длиннее 7000", len(оп) <= 7000, True)
проверь("нет запрещённого амперсанда", "&" in оп, False)
проверь("нет символа номера", "№" in оп, False)
проверь("нет косых черт", ("/" in оп or "\\" in оп), False)

print("\n3а. Предохранитель: без разрешения Ирика фид пустой")
пустой = cian.фид(cian.загрузить())
корень3 = ET.fromstring(пустой)
проверь("К_ПУБЛИКАЦИИ пуст по умолчанию", cian.К_ПУБЛИКАЦИИ, ())
проверь("в фид не попал ни один участок", len(корень3.findall("object")), 0)
проверь("но фид остаётся валидным XML", корень3.tag, "feed")
сохранённое = cian.К_ПУБЛИКАЦИИ
cian.К_ПУБЛИКАЦИИ = ("3", "4")
частичный = ET.fromstring(cian.фид(cian.разобрать(ПОДСТАВНАЯ)))
проверь("разрешённый участок попадает", [o.findtext("ExternalId") for o in частичный.findall("object")],
        ["schekinskie-berega-3"])
cian.К_ПУБЛИКАЦИИ = сохранённое

print("\n4. Фид на живой шахматке")
живой = cian.фид(cian.загрузить(), только_разрешённые=False)
корень2 = ET.fromstring(живой)
объектов = корень2.findall("object")
проверь("фид разбирается как XML", len(объектов) > 0, True)
проверь("у всех объектов есть цена", all(o.findtext("BargainTerms/Price") for o in объектов), True)
проверь("у всех есть телефон", all(o.findtext("Phones/PhoneSchema/Number") for o in объектов), True)
проверь("внешние id уникальны",
        len({o.findtext("ExternalId") for o in объектов}), len(объектов))
print(f"  · размер фида: {len(живой)} байт, объектов: {len(объектов)}")

print("\n" + ("ВСЁ ЗЕЛЁНОЕ" if not провалов else f"ПРОВАЛОВ: {провалов}"))
sys.exit(1 if провалов else 0)
