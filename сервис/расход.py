"""Учёт расхода на токены — общий журнал для всех контейнеров агента.

Требование Ирика 09.09.2026: в ежедневном отчёте должно быть видно, сколько
долларов агент потратил за сутки.

Почему журнал в Битриксе, а не в файле. Агент живёт в ПЯТИ контейнерах:
вебхук (в нём же идут все разборы чатов — их около 90 в сутки) и четыре
cron-сервиса (утро/вечер × два кабинета). Общей файловой системы у них нет:
том Railway привязан к одному сервису, а /tmp умирает вместе с контейнером
при каждом передеплое — их бывает 3–4 в сутки. Расход при этом печатался
только в логи Railway, и логи стираются вместе с деплоем.

Битрикс доступен всем пяти по одному и тому же вебхуку, переживает любой
деплой и уже используется этими же процессами. Поэтому журнал — таймлайн
одной служебной карточки (сделка 3139, стадия LOSE, причина «нецелевой»):
в воронке она не участвует и в счётчики отчёта не попадает, потому что они
считают движение по MOVED_TIME за сутки, а эта карточка не движется.

Формат строки машинный, одной строкой, чтобы разбор не зависел от языка:

    РАСХОД|<unix>|<вид>|<кабинет>|<модель>|<usd>|<вход>|<кэш_чт>|<кэш_зап>|<выход>

Запись НИКОГДА не роняет прогон: не удалось записать — строка ушла в stderr,
работа продолжается. Потерянная цифра расхода дешевле сорванного ответа
клиенту.
"""

from __future__ import annotations

import os
import sys
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from интеграции.bitrix import Bitrix  # noqa: E402

МСК = timezone(timedelta(hours=3))

# Служебная карточка-журнал. Заведена 09.09.2026, см. её COMMENTS.
СДЕЛКА_УЧЁТА = os.environ.get("СДЕЛКА_УЧЁТА_РАСХОДА", "3139")

МЕТКА = "РАСХОД|"

# Сколько дней держим записи. Отчёту нужны сутки, три дня — запас на случай
# пропущенного вечернего прогона, чтобы расход не потерялся совсем.
ХРАНИМ_ДНЕЙ = int(os.environ.get("ХРАНИМ_ДНЕЙ_РАСХОДА", "3"))


def строка(
    usd: float,
    вид: str,
    кабинет: str,
    модель: str,
    вход: int = 0,
    кэш_чт: int = 0,
    кэш_зап: int = 0,
    выход: int = 0,
    когда: float | None = None,
) -> str:
    """Одна запись журнала. Разделитель — вертикальная черта, без пробелов."""
    метки = [
        МЕТКА.rstrip("|"),
        f"{int(когда or time.time())}",
        вид or "?",
        кабинет or "?",
        модель or "?",
        f"{float(usd or 0):.4f}",
        str(int(вход or 0)),
        str(int(кэш_чт or 0)),
        str(int(кэш_зап or 0)),
        str(int(выход or 0)),
    ]
    return "|".join(метки)


def разобрать(текст: str) -> dict | None:
    """Строка журнала → запись. Чужой комментарий в таймлайне вернёт None."""
    for кусок in (текст or "").splitlines():
        кусок = кусок.strip()
        if not кусок.startswith(МЕТКА):
            continue
        поля = кусок.split("|")
        if len(поля) < 6:
            continue
        try:
            запись = {
                "когда": float(поля[1]),
                "вид": поля[2],
                "кабинет": поля[3],
                "модель": поля[4],
                "usd": float(поля[5]),
            }
        except (TypeError, ValueError):
            continue
        for имя, номер in (("вход", 6), ("кэш_чт", 7), ("кэш_зап", 8), ("выход", 9)):
            try:
                запись[имя] = int(поля[номер])
            except (IndexError, TypeError, ValueError):
                запись[имя] = 0
        return запись
    return None


def записать(
    usd: float | None,
    вид: str,
    кабинет: str,
    модель: str,
    вход: int = 0,
    кэш_чт: int = 0,
    кэш_зап: int = 0,
    выход: int = 0,
) -> bool:
    """Дописать расход в журнал. Сбой не роняет прогон — только stderr."""
    if usd is None:
        return False
    b = None
    try:
        b = Bitrix()
        b.timeline_comment_add(
            СДЕЛКА_УЧЁТА,
            строка(usd, вид, кабинет, модель, вход, кэш_чт, кэш_зап, выход),
        )
        return True
    except Exception as ошибка:  # noqa: BLE001 — цифра дешевле сорванной работы
        print(f"[расход] не записан: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
        return False
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass


def _комментарии(b: Bitrix, предел: int = 1000) -> list[dict]:
    собранные: list[dict] = []
    старт = 0
    while len(собранные) < предел:
        порция = b.call(
            "crm.timeline.comment.list",
            {
                "filter": {"ENTITY_ID": int(СДЕЛКА_УЧЁТА), "ENTITY_TYPE": "deal"},
                "order": {"ID": "DESC"},
                "start": старт,
            },
        )
        порция = порция or []
        собранные.extend(порция)
        if len(порция) < 50:
            break
        старт += 50
    return собранные


def за_период(начало: float, конец: float) -> dict:
    """Сумма расхода за окно: доллары, число запусков, разбивка по моделям."""
    пусто = {"usd": 0.0, "запусков": 0, "по_моделям": {}, "по_видам": {}, "записей_всего": 0}
    b = None
    try:
        b = Bitrix()
        комментарии = _комментарии(b)
    except Exception as ошибка:  # noqa: BLE001 — отчёт важнее цифры расхода
        print(f"[расход] журнал не прочитан: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
        return пусто
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass

    итог = dict(пусто)
    итог["по_моделям"] = {}
    итог["по_видам"] = {}
    for к in комментарии:
        запись = разобрать(к.get("COMMENT") or "")
        if not запись:
            continue
        итог["записей_всего"] += 1
        if not (начало <= запись["когда"] <= конец):
            continue
        итог["usd"] += запись["usd"]
        итог["запусков"] += 1
        м = запись["модель"]
        итог["по_моделям"][м] = round(итог["по_моделям"].get(м, 0.0) + запись["usd"], 4)
        в = запись["вид"]
        итог["по_видам"][в] = round(итог["по_видам"].get(в, 0.0) + запись["usd"], 4)
    итог["usd"] = round(итог["usd"], 2)
    return итог


def подчистить(старше_дней: int = ХРАНИМ_ДНЕЙ) -> int:
    """Удалить старые записи журнала, чтобы карточка не росла вечно."""
    порог = time.time() - старше_дней * 86400
    удалено = 0
    b = None
    try:
        b = Bitrix()
        for к in _комментарии(b):
            запись = разобрать(к.get("COMMENT") or "")
            if not запись or запись["когда"] >= порог:
                continue
            try:
                b.call("crm.timeline.comment.delete", {"id": к.get("ID")})
                удалено += 1
            except Exception:  # noqa: BLE001 — одна запись не роняет уборку
                continue
    except Exception as ошибка:  # noqa: BLE001
        print(f"[расход] уборка не прошла: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass
    return удалено


def словами(итог: dict) -> str:
    """Строка расхода для отчёта."""
    if not итог.get("запусков"):
        return "*Расход на токены:* нет данных за сутки"

    модели = " · ".join(
        f"{м.replace('claude-', '')} ${s:.2f}"
        for м, s in sorted(итог["по_моделям"].items(), key=lambda x: -x[1])
    )
    return (
        f"*Расход на токены:* ${итог['usd']:.2f} за сутки "
        f"({итог['запусков']} запусков модели)"
        + (f"\n  {модели}" if модели else "")
    )


def main() -> int:
    """python сервис/расход.py [часов] — показать расход, ничего не меняя."""
    часов = int(sys.argv[1]) if len(sys.argv) > 1 else 24
    конец = datetime.now(МСК).timestamp()
    итог = за_период(конец - часов * 3600, конец)
    print(словами(итог))
    print(f"(всего записей в журнале: {итог['записей_всего']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
