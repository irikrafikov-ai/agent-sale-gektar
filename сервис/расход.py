"""Учёт расхода на токены — общий журнал для всех контейнеров агента.

Требование Ирика 09.09.2026: в ежедневном отчёте должно быть видно, сколько
долларов агент потратил за сутки.

Почему журнал в Битриксе, а не в файле. Агент живёт в ПЯТИ контейнерах:
вебхук (в нём же идут все разборы чатов — их около 90 в сутки) и четыре
cron-сервиса (утро/вечер × два кабинета). Общей файловой системы у них нет:
том Railway привязан к одному сервису, а /tmp умирает вместе с контейнером
при каждом передеплое — их бывает 3–4 в сутки. Расход при этом печатался
только в логи Railway, и логи стираются вместе с деплоем.

Битрикс доступен всем пяти по одному и тому же вебхуку, переживает любой
деплой и уже используется этими же процессами. Поэтому журнал — таймлайн
одной служебной карточки (сделка 3139, стадия LOSE, причина «нецелевой»):
в воронке она не участвует и в счётчики отчёта не попадает, потому что они
считают движение по MOVED_TIME за сутки, а эта карточка не движется.

Формат строки машинный, одной строкой, чтобы разбор не зависел от языка:

    РАСХОД|<unix>|<вид>|<кабинет>|<модель>|<usd>|<вход>|<кэш_чт>|<кэш_зап>|<выход>

Вторая цифра — за месяц (распоряжение Ирика 18.09.2026: «за день потратил
и всего за месяц потратил»). Сырые строки за месяц — это сотни записей, и
читать их каждый вечер целиком расточительно, поэтому вечерний прогон
закрывает вчерашний календарный день одной строкой-итогом:

    ИТОГ_ДНЯ|<unix>|<ГГГГ-ММ-ДД>|<usd>|<запусков>

Сумма за месяц = итоги закрытых дней + сырые строки дней, ещё не закрытых.
Сырые строки старше трёх дней после этого убираются, итоги живут год.
Журнал ведётся с 09.09.2026 — за 1–8 сентября цифр нет, отчёт честно
пишет, с какого дня считает.

Запись НИКОГДА не роняет прогон: не удалось записать — строка ушла в stderr,
работа продолжается. Потерянная цифра расхода дешевле сорванного ответа
клиенту.
"""

from __future__ import annotations

import os
import sys
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from интеграции.bitrix import Bitrix  # noqa: E402

МСК = timezone(timedelta(hours=3))

# Служебная карточка-журнал. Заведена 09.09.2026, см. её COMMENTS.
СДЕЛКА_УЧЁТА = os.environ.get("СДЕЛКА_УЧЁТА_РАСХОДА", "3139")

МЕТКА = "РАСХОД|"

# Сколько дней держим записи. Отчёту нужны сутки, три дня — запас на случай
# пропущенного вечернего прогона, чтобы расход не потерялся совсем.
ХРАНИМ_ДНЕЙ = int(os.environ.get("ХРАНИМ_ДНЕЙ_РАСХОДА", "3"))


def строка(
    usd: float,
    вид: str,
    кабинет: str,
    модель: str,
    вход: int = 0,
    кэш_чт: int = 0,
    кэш_зап: int = 0,
    выход: int = 0,
    когда: float | None = None,
) -> str:
    """Одна запись журнала. Разделитель — вертикальная черта, без пробелов."""
    метки = [
        МЕТКА.rstrip("|"),
        f"{int(когда or time.time())}",
        вид or "?",
        кабинет or "?",
        модель or "?",
        f"{float(usd or 0):.4f}",
        str(int(вход or 0)),
        str(int(кэш_чт or 0)),
        str(int(кэш_зап or 0)),
        str(int(выход or 0)),
    ]
    return "|".join(метки)


def разобрать(текст: str) -> dict | None:
    """Строка журнала → запись. Чужой комментарий в таймлайне вернёт None."""
    for кусок in (текст or "").splitlines():
        кусок = кусок.strip()
        if not кусок.startswith(МЕТКА):
            continue
        поля = кусок.split("|")
        if len(поля) < 6:
            continue
        try:
            запись = {
                "когда": float(поля[1]),
                "вид": поля[2],
                "кабинет": поля[3],
                "модель": поля[4],
                "usd": float(поля[5]),
            }
        except (TypeError, ValueError):
            continue
        for имя, номер in (("вход", 6), ("кэш_чт", 7), ("кэш_зап", 8), ("выход", 9)):
            try:
                запись[имя] = int(поля[номер])
            except (IndexError, TypeError, ValueError):
                запись[имя] = 0
        return запись
    return None


МЕТКА_ДНЯ = "ИТОГ_ДНЯ|"


def разобрать_итог_дня(текст: str) -> dict | None:
    т = (текст or "").strip()
    if not т.startswith(МЕТКА_ДНЯ):
        return None
    поля = т.split("|")
    if len(поля) < 5:
        return None
    try:
        return {
            "когда": float(поля[1]),
            "дата": поля[2].strip(),
            "usd": float(поля[3]),
            "запусков": int(поля[4]),
        }
    except (TypeError, ValueError):
        return None


def _дата_мск(unix: float) -> str:
    return datetime.fromtimestamp(unix, МСК).strftime("%Y-%m-%d")


def записать(
    usd: float | None,
    вид: str,
    кабинет: str,
    модель: str,
    вход: int = 0,
    кэш_чт: int = 0,
    кэш_зап: int = 0,
    выход: int = 0,
) -> bool:
    """Дописать расход в журнал. Сбой не роняет прогон — только stderr."""
    if usd is None:
        return False
    b = None
    try:
        b = Bitrix()
        b.timeline_comment_add(
            СДЕЛКА_УЧЁТА,
            строка(usd, вид, кабинет, модель, вход, кэш_чт, кэш_зап, выход),
        )
        return True
    except Exception as ошибка:  # noqa: BLE001 — цифра дешевле сорванной работы
        print(f"[расход] не записан: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
        return False
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass


def _комментарии(b: Bitrix, предел: int = 1000) -> list[dict]:
    собранные: list[dict] = []
    старт = 0
    while len(собранные) < предел:
        порция = b.call(
            "crm.timeline.comment.list",
            {
                "filter": {"ENTITY_ID": int(СДЕЛКА_УЧЁТА), "ENTITY_TYPE": "deal"},
                "order": {"ID": "DESC"},
                "start": старт,
            },
        )
        порция = порция or []
        собранные.extend(порция)
        if len(порция) < 50:
            break
        старт += 50
    return собранные


def за_период(начало: float, конец: float) -> dict:
    """Сумма расхода за окно: доллары, число запусков, разбивка по моделям."""
    пусто = {"usd": 0.0, "запусков": 0, "по_моделям": {}, "по_видам": {}, "записей_всего": 0}
    b = None
    try:
        b = Bitrix()
        комментарии = _комментарии(b)
    except Exception as ошибка:  # noqa: BLE001 — отчёт важнее цифры расхода
        print(f"[расход] журнал не прочитан: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
        return пусто
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass

    итог = dict(пусто)
    итог["по_моделям"] = {}
    итог["по_видам"] = {}
    for к in комментарии:
        запись = разобрать(к.get("COMMENT") or "")
        if not запись:
            continue
        итог["записей_всего"] += 1
        if not (начало <= запись["когда"] <= конец):
            continue
        итог["usd"] += запись["usd"]
        итог["запусков"] += 1
        м = запись["модель"]
        итог["по_моделям"][м] = round(итог["по_моделям"].get(м, 0.0) + запись["usd"], 4)
        в = запись["вид"]
        итог["по_видам"][в] = round(итог["по_видам"].get(в, 0.0) + запись["usd"], 4)
    итог["usd"] = round(итог["usd"], 2)
    return итог


def за_месяц(конец: float | None = None) -> dict:
    """Расход с 1-го числа месяца по момент «конец» (по умолчанию сейчас).

    Закрытые дни берутся из строк ИТОГ_ДНЯ, остальные — из сырых строк.
    «с_какого_дня» — первая дата, за которую в журнале вообще есть данные:
    если она позже 1-го числа, отчёт скажет, что часть месяца не учтена.
    """
    конец = конец or time.time()
    первое = datetime.fromtimestamp(конец, МСК).replace(
        day=1, hour=0, minute=0, second=0, microsecond=0
    )
    пусто = {"usd": 0.0, "дней": 0, "с_какого_дня": None, "по": _дата_мск(конец), "месяц": первое.strftime("%m.%Y")}
    b = None
    try:
        b = Bitrix()
        комментарии = _комментарии(b, предел=3000)
    except Exception as ошибка:  # noqa: BLE001
        print(f"[расход] месяц не собран: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
        return пусто
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass

    закрытые: dict[str, float] = {}
    сырые: dict[str, float] = {}
    for к in комментарии:
        текст = к.get("COMMENT") or ""
        if итог := разобрать_итог_дня(текст):
            # дубль итога за день (перезапуск вечера) — берём последний
            if итог["дата"] not in закрытые:
                закрытые[итог["дата"]] = итог["usd"]
            continue
        if запись := разобрать(текст):
            if запись["когда"] <= конец:
                д = _дата_мск(запись["когда"])
                сырые[д] = сырые.get(д, 0.0) + запись["usd"]

    по_дням = {**{д: v for д, v in сырые.items()}, **закрытые}
    в_месяце = {д: v for д, v in по_дням.items() if д >= первое.strftime("%Y-%m-%d") and д <= _дата_мск(конец)}
    return {
        **пусто,
        "usd": round(sum(в_месяце.values()), 2),
        "дней": len(в_месяце),
        "с_какого_дня": min(в_месяце) if в_месяце else None,
        "по_дням": dict(sorted(в_месяце.items())),
    }


def закрыть_день(дата: str | None = None) -> float | None:
    """Свести сырые строки календарного дня в одну ИТОГ_ДНЯ.

    По умолчанию закрывается ВЧЕРАШНИЙ день: сегодняшний ещё идёт (вечерний
    прогон в 18:30, а разборы чатов бывают и в 23:00). Повторный вызов за ту
    же дату старый итог удаляет и пишет новый.
    """
    дата = дата or _дата_мск(time.time() - 86400)
    b = None
    try:
        b = Bitrix()
        usd = 0.0
        запусков = 0
        старые: list[str] = []
        for к in _комментарии(b, предел=3000):
            текст = к.get("COMMENT") or ""
            if (итог := разобрать_итог_дня(текст)) and итог["дата"] == дата:
                старые.append(к.get("ID"))
                continue
            if (запись := разобрать(текст)) and _дата_мск(запись["когда"]) == дата:
                usd += запись["usd"]
                запусков += 1
        if not запусков and not старые:
            return None
        for ид in старые:
            try:
                b.call("crm.timeline.comment.delete", {"id": ид})
            except Exception:  # noqa: BLE001
                pass
        if запусков:
            b.timeline_comment_add(
                СДЕЛКА_УЧЁТА, f"{МЕТКА_ДНЯ}{int(time.time())}|{дата}|{usd:.4f}|{запусков}"
            )
        return round(usd, 2)
    except Exception as ошибка:  # noqa: BLE001
        print(f"[расход] день {дата} не закрыт: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
        return None
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass


def подчистить(старше_дней: int = ХРАНИМ_ДНЕЙ) -> int:
    """Удалить старые записи журнала, чтобы карточка не росла вечно."""
    порог = time.time() - старше_дней * 86400
    удалено = 0
    b = None
    try:
        b = Bitrix()
        все = _комментарии(b, предел=3000)
        закрытые = {и["дата"] for к in все if (и := разобрать_итог_дня(к.get("COMMENT") or ""))}
        for к in все:
            запись = разобрать(к.get("COMMENT") or "")
            if not запись or запись["когда"] >= порог:
                continue
            # Сырая строка нужна, пока её день не сведён в ИТОГ_ДНЯ —
            # иначе сумма за месяц потеряет этот день.
            if _дата_мск(запись["когда"]) not in закрытые:
                continue
            try:
                b.call("crm.timeline.comment.delete", {"id": к.get("ID")})
                удалено += 1
            except Exception:  # noqa: BLE001 — одна запись не роняет уборку
                continue
    except Exception as ошибка:  # noqa: BLE001
        print(f"[расход] уборка не прошла: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass
    return удалено


def словами(итог: dict) -> str:
    """Строка расхода для отчёта."""
    if not итог.get("запусков"):
        return "*Расход на токены:* нет данных за сутки"

    модели = " · ".join(
        f"{м.replace('claude-', '')} ${s:.2f}"
        for м, s in sorted(итог["по_моделям"].items(), key=lambda x: -x[1])
    )
    строка = (
        f"*Расход на токены:* ${итог['usd']:.2f} за сутки "
        f"({итог['запусков']} запусков модели)"
        + (f"\n  {модели}" if модели else "")
    )
    if месяц := итог.get("месяц"):
        строка += "\n" + месяц_словами(месяц)
    return строка


def месяц_словами(месяц: dict) -> str:
    """Вторая цифра — за месяц с 1-го числа (распоряжение Ирика 18.09.2026)."""
    if not месяц or not месяц.get("дней"):
        return "*За месяц:* данных нет"
    первое = месяц["с_какого_дня"] or ""
    по = месяц.get("по") or ""
    def дм(д: str) -> str:
        return f"{д[8:10]}.{д[5:7]}" if len(д) >= 10 else д
    оговорка = ""
    if первое and первое[8:10] != "01":
        оговорка = f" — журнал ведётся с {дм(первое)}, раньше цифр нет"
    return (
        f"*За месяц (с {дм(первое)} по {дм(по)}):* ${месяц['usd']:.2f} "
        f"за {месяц['дней']} дн., в среднем ${месяц['usd'] / месяц['дней']:.2f}/день"
        + оговорка
    )


def main() -> int:
    """python сервис/расход.py [часов] — показать расход, ничего не меняя."""
    часов = int(sys.argv[1]) if len(sys.argv) > 1 else 24
    конец = datetime.now(МСК).timestamp()
    итог = за_период(конец - часов * 3600, конец)
    print(словами(итог))
    print(f"(всего записей в журнале: {итог['записей_всего']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


# ── Молчаливые разборы ─────────────────────────────────────────────────────
#
# Требование Ирика 10.09.2026. Дважды подряд агент заканчивал разбор чата,
# ничего не отправив и не объяснив почему: 07.09 по Олегу, 10.09 по Наталье
# Надельниченко. Оба раза вебхук отрабатывал верно — молчала модель, и её
# решение оставалось невидимым: ни в CRM, ни в отчёте, только в логах Railway.
#
# 07.09 правило «промолчал — напиши почему» добавили в бриф, и модель его
# проигнорировала. Значит текстовой инструкции мало: факт молчания фиксирует
# КОД, а не просьба к модели. Здесь тот же журнал, что и у расхода, — он
# общий для всех контейнеров и переживает деплой.

МЕТКА_МОЛЧАНИЯ = "МОЛЧАНИЕ|"


def записать_молчание(chat_id: str, повод: str, кабинет: str) -> bool:
    """Отметить разбор, который закончился ничем и без объяснения."""
    строка_ = "|".join(
        [
            МЕТКА_МОЛЧАНИЯ.rstrip("|"),
            str(int(time.time())),
            кабинет or "?",
            chat_id or "?",
            " ".join((повод or "без повода").split())[:120],
        ]
    )
    b = None
    try:
        b = Bitrix()
        b.timeline_comment_add(СДЕЛКА_УЧЁТА, строка_)
        return True
    except Exception as ошибка:  # noqa: BLE001 — учёт не важнее работы
        print(f"[молчание] не записано: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
        return False
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass


def разобрать_молчание(текст: str) -> dict | None:
    for кусок in (текст or "").splitlines():
        кусок = кусок.strip()
        if not кусок.startswith(МЕТКА_МОЛЧАНИЯ):
            continue
        поля = кусок.split("|")
        if len(поля) < 5:
            continue
        try:
            return {
                "когда": float(поля[1]),
                "кабинет": поля[2],
                "chat_id": поля[3],
                "повод": поля[4],
            }
        except (TypeError, ValueError):
            continue
    return None


def молчания_за_период(начало: float, конец: float) -> list[dict]:
    """Молчаливые разборы за окно — для вечернего отчёта."""
    b = None
    try:
        b = Bitrix()
        комментарии = _комментарии(b)
    except Exception as ошибка:  # noqa: BLE001 — отчёт важнее строки
        print(f"[молчание] журнал не прочитан: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
        return []
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass

    найдено = []
    for к in комментарии:
        запись = разобрать_молчание(к.get("COMMENT") or "")
        if запись and начало <= запись["когда"] <= конец:
            найдено.append(запись)
    return найдено
