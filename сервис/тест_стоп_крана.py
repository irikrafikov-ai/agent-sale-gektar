"""Стоп-кран «в чате ответили без нас».

Проверяет ровно то, за что этот кран отвечает: блокировать отправку, когда
Ирик ответил клиенту сам, и НЕ мешать во всех остальных случаях — иначе
встанет вечерний прогрев, а это дороже дубля.

    python сервис/тест_стоп_крана.py
"""

import sys, time, types, os
# SDK на Маке не установлен, а проверяемая логика от него не зависит — заглушка.
_sdk = types.ModuleType("claude_agent_sdk")
_sdk.create_sdk_mcp_server = lambda *a, **k: None
_sdk.tool = lambda *a, **k: (lambda f: f)
sys.modules["claude_agent_sdk"] = _sdk
sys.path.insert(0, "сервис")
os.environ.setdefault("AVITO_CLIENT_ID", "x"); os.environ.setdefault("AVITO_CLIENT_SECRET", "x")
import инструменты as и

СЕЙЧАС = time.time()
МЕНЯ = 84069402
КЛИЕНТ = 85992372

class Кли:
    user_id = МЕНЯ
    def __init__(self, msgs): self.msgs = msgs
    def chat_messages(self, chat_id, limit=10): return self.msgs

def м(id_, кто, когда, текст): return {"id": id_, "author_id": кто, "created": когда, "content": {"text": текст}}

провал = 0
def проверь(имя, факт, ожидание):
    global провал
    ок = (факт is not None) == ожидание
    print(("  ✅ " if ок else "  ❌ ") + имя + ("" if ок else f"  (ждали блок={ожидание}, вышло={факт is not None})"))
    if not ок: провал += 1

и._наши_id.clear()

# 1. Ирик ответил сам 40 сек назад, после слова клиента → БЛОК
проверь("Ирик ответил параллельно",
        и._чужое_исходящее(Кли([м("a", КЛИЕНТ, СЕЙЧАС-120, "жду ответ по маткапиталу"),
                                м("b", МЕНЯ, СЕЙЧАС-40, "По поводу мат капитала...")]), "c"), True)

# 2. Наше собственное сообщение этого прогона → НЕ блок
и._наши_id.add("b")
проверь("наше же сообщение не блокирует",
        и._чужое_исходящее(Кли([м("a", КЛИЕНТ, СЕЙЧАС-120, "вопрос"),
                                м("b", МЕНЯ, СЕЙЧАС-40, "ответ агента")]), "c"), False)
и._наши_id.clear()

# 3. Старое касание 3 дня назад, клиент молчит → НЕ блок (иначе прогрев умрёт)
проверь("старое касание не блокирует прогрев",
        и._чужое_исходящее(Кли([м("a", КЛИЕНТ, СЕЙЧАС-900000, "спасибо"),
                                м("b", МЕНЯ, СЕЙЧАС-259200, "касание 2")]), "c"), False)

# 4. Клиент ответил последним → НЕ блок
проверь("последнее слово клиента не блокирует",
        и._чужое_исходящее(Кли([м("b", МЕНЯ, СЕЙЧАС-300, "наш вопрос"),
                                м("a", КЛИЕНТ, СЕЙЧАС-60, "да, интересно")]), "c"), False)

# 5. Сеть отвалилась → НЕ блок, отправку не ломаем
class Битый:
    user_id = МЕНЯ
    def chat_messages(self, *a, **k): raise RuntimeError("502")
проверь("сбой сети не блокирует отправку", и._чужое_исходящее(Битый(), "c"), False)

print("\nПРОВАЛОВ:", провал)
sys.exit(1 if провал else 0)
