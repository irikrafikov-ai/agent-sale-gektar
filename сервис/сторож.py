"""Сторож молчания: чат, где ждут ответа дольше положенного, не должен пропасть.

За 21–23.08 пятеро клиентов ждали ответа часами — Степан, Ilia, Ольга, Максим,
Ангелина. Причины были разные каждый раз: незнакомая формулировка системного
сообщения Авито, ошибочная пометка «дубль» в Битриксе, убитый пушем прогон.
Симптом был один и тот же — непрочитанный чат. И каждый раз находил его Ирик,
а не система.

Чинить по одной причине бессмысленно: следующая будет новой. Сторож смотрит на
симптом и потому ловит любую причину сразу, включая те, которых ещё не было.

Запускается раз в час из вебхука. Ничего не отправляет клиентам — только
считает и говорит Ирику.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
from dataclasses import dataclass
from pathlib import Path
from datetime import datetime, timedelta, timezone

МСК = timezone(timedelta(hours=3))

# Сколько ждём, прежде чем считать молчание проблемой. Пятнадцать минут —
# компромисс: вебхук отвечает за полторы минуты, прогон может думать дольше,
# а человек начинает считать себя проигнорированным примерно через четверть
# часа. Меньше — будет шуметь на нормальной работе.
ПОРОГ_МИНУТ = int(os.environ.get("СТОРОЖ_ПОРОГ_МИНУТ", "15"))

# Ночью не будим: клиент, написавший в 3:00, не ждёт ответа в 3:15, а звук
# уведомления в это время обесценивает канал быстрее, чем что-либо ещё.
ТИХО_С, ТИХО_ДО = 22, 9

# Верхняя граница окна. Всё, что ждёт дольше суток, — это не «кого-то
# игнорируют прямо сейчас», а накопленная база: ею занимаются касания и
# вечерний отчёт, а не почасовой алерт. 25.08 без этой границы сторож прислал
# 164 чата, включая ожидающий 96 часов, — такой список не читают вообще.
ПОТОЛОК_ЧАСОВ = int(os.environ.get("СТОРОЖ_ПОТОЛОК_ЧАСОВ", "24"))

# Сколько чатов проверяем. Список отсортирован по свежести, поэтому первые
# двести с запасом покрывают всё, что могло протухнуть за час.
ГЛУБИНА = int(os.environ.get("СТОРОЖ_ГЛУБИНА", "200"))


ССЫЛКА_В_ТЕКСТЕ = re.compile(r"https?://\S+")


def _без_ссылок(текст: str, предел: int = 110) -> str:
    """Цитата последнего сообщения — без URL и без обрубков URL.

    25.08 Ирик получил алерт со ссылкой https://avito.ru/profile/messenger/chann
    — обрезанной ровно посередине: системное сообщение Авито «перейдите в Авито
    мессенджер» содержит длинный адрес, а мы резали цитату по символам.
    Телеграм из обрубка сделал ссылку, ссылка вела в 404.

    Адрес чата мы и так даём отдельной строкой и собираем его сами, поэтому
    чужие ссылки из цитаты просто убираем: в ней важен смысл, а не URL.
    """
    текст = ССЫЛКА_В_ТЕКСТЕ.sub("…", (текст or "").replace("\n", " ")).strip()
    return текст if len(текст) <= предел else текст[: предел - 1].rstrip() + "…"


@dataclass(frozen=True)
class Забытый:
    chat_id: str
    имя: str
    кабинет: str
    минут: int
    последнее: str

    @property
    def ссылка(self) -> str:
        return f"https://www.avito.ru/profile/messenger/channel/{self.chat_id}"

    def строка(self) -> str:
        часы = f"{self.минут // 60} ч {self.минут % 60} мин" if self.минут >= 60 else f"{self.минут} мин"
        return (
            f"· {self.имя} ({self.кабинет}) — ждёт {часы}\n"
            f"  {self.ссылка}\n"
            f"  «{_без_ссылок(self.последнее)}»"
        )


def сейчас_тихо(момент: datetime | None = None) -> bool:
    час = (момент or datetime.now(МСК)).hour
    return час >= ТИХО_С or час < ТИХО_ДО


def забытые(чаты: list[dict], наш_id: int, кабинет: str, момент: datetime | None = None) -> list[Забытый]:
    """Чаты, где последнее слово не наше и висит дольше порога.

    Системные сообщения Авито считаются наравне с репликами клиента: «посмотрел
    номер» и «создал чат» — это тоже ожидание ответа, и именно на них мы
    трижды и промолчали.
    """
    момент = момент or datetime.now(МСК)
    порог = момент - timedelta(minutes=ПОРОГ_МИНУТ)
    итог: list[Забытый] = []

    for чат in чаты:
        последнее = чат.get("last_message") or {}
        if последнее.get("author_id") == наш_id:
            continue  # ответили — ждать нечего

        когда_ts = последнее.get("created")
        if not когда_ts:
            continue
        когда = datetime.fromtimestamp(когда_ts, МСК)
        if когда > порог:
            continue  # ещё в пределах нормы, агент может быть в работе
        if когда < момент - timedelta(hours=ПОТОЛОК_ЧАСОВ):
            continue  # старше суток — это база, а не срочность

        собеседник = next(
            (u for u in чат.get("users", []) if u.get("id") != наш_id), {}
        )
        итог.append(
            Забытый(
                chat_id=чат.get("id", ""),
                имя=(собеседник.get("name") or "без имени"),
                кабинет=кабинет,
                минут=int((момент - когда).total_seconds() // 60),
                последнее=((последнее.get("content") or {}).get("text") or последнее.get("type", "")),
            )
        )

    итог.sort(key=lambda з: з.минут, reverse=True)
    return итог


def отчёт(все_забытые: list[Забытый]) -> str:
    if not все_забытые:
        return ""
    шапка = (
        f"🔔 Ждут ответа дольше {ПОРОГ_МИНУТ} минут: {len(все_забытые)}\n\n"
        if len(все_забытые) > 1
        else "🔔 Клиент ждёт ответа\n\n"
    )
    тела = "\n\n".join(з.строка() for з in все_забытые[:15])
    хвост = (
        f"\n\n…и ещё {len(все_забытые) - 15}. Столько сразу — похоже на сбой, а не на задержку."
        if len(все_забытые) > 15
        else ""
    )
    return шапка + тела + хвост

# ── Память о разобранном ──────────────────────────────────────────────────
#
# 02.09 сторож шесть раз подряд, каждый час, брал в разбор один и тот же чат
# Анны: 1034 минуты ожидания, потом 1094, 1154, 1214, 1274, 1334. Каждый раз
# это был полноценный запуск модели, каждый раз агент решал не отвечать (в
# Битриксе стоял отказ), и каждый раз через час чат находился снова — для
# сторожа ведь ничего не изменилось. Шесть запусков Opus, чтобы шестикратно
# убедиться в том, что клиент молчит.
#
# Лечится одним фактом в памяти: какое последнее сообщение мы в этом чате
# видели. Совпало — значит с прошлого разбора не произошло ничего, и повтор
# не даст другого результата. Появилась новая реплика — разбираем немедленно,
# как и раньше.
#
# Храним ХЭШ, а не текст: в файле не должно лежать переписки клиентов.
# Файл в /tmp переживает разборы, но не переживает передеплой — тот же
# осознанный размен, что и у ПАМЯТЬ_ЛИДОВ: после деплоя возможен один лишний
# разбор, зато нет базы, которую надо поднимать и обслуживать.
ПАМЯТЬ_РАЗБОРОВ = Path(os.environ.get("ПАМЯТЬ_РАЗБОРОВ", "/tmp/сторож-разобрано.json"))


def _отпечаток(последнее: str) -> str:
    return hashlib.sha1((последнее or "").encode("utf-8")).hexdigest()[:16]


def _память() -> dict:
    try:
        return json.loads(ПАМЯТЬ_РАЗБОРОВ.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001 — нет файла или он побит: считаем, что не разбирали
        return {}


def новые(забытые: list[Забытый]) -> list[Забытый]:
    """Оставить тех, в чьих чатах с прошлого разбора что-то изменилось.

    Сбой чтения памяти трактуем в пользу клиента: лишний разбор стоит токенов,
    пропущенный человек — сделки. Поэтому любая ошибка означает «не разбирали».
    """
    память = _память()

    def было(chat_id: str) -> str | None:
        # В памяти лежит пара [отпечаток, когда] — сравнивать надо с первым
        # элементом. Сравнение со всей парой молча не совпадало никогда, и
        # фильтр пропускал всех: поймано тестом до выката.
        запись = память.get(chat_id)
        return запись[0] if isinstance(запись, list) and запись else None

    return [з for з in забытые if было(з.chat_id) != _отпечаток(з.последнее)]


def запомнить(забытые: list[Забытый]) -> None:
    """Отметить разобранные. Старше двух суток выбрасываем: сторож всё равно
    не смотрит дальше ПОТОЛОК_ЧАСОВ, а файл не должен расти вечно."""
    память = _память()
    сейчас = datetime.now(МСК)
    свежие = {
        к: v
        for к, v in память.items()
        if isinstance(v, list)
        and len(v) == 2
        and (сейчас - datetime.fromisoformat(v[1])).days < 2
    }
    for з in забытые:
        свежие[з.chat_id] = [_отпечаток(з.последнее), сейчас.isoformat()]
    try:
        ПАМЯТЬ_РАЗБОРОВ.write_text(
            json.dumps(свежие, ensure_ascii=False), encoding="utf-8"
        )
    except Exception:  # noqa: BLE001 — не записали: получим лишний разбор, не потерю
        pass
