def обновить_базу_знаний() -> str:
    """Клонирует или обновляет репозиторий базы знаний. Возвращает статус для отчёта."""
    url = os.environ.get("KB_REPO_URL")
    if not url:
        return "⚠️ KB_REPO_URL не задан — база знаний недоступна"

    token = os.environ.get("KB_TOKEN")
    if token and url.startswith("https://"):
        url = url.replace("https://", f"https://x-access-token:{token}@", 1)

    try:
        if (БАЗА_ЗНАНИЙ / ".git").exists():
            subprocess.run(
                ["git", "-C", str(БАЗА_ЗНАНИЙ), "fetch", "--quiet", "origin"], check=True, timeout=120
            )
            subprocess.run(
                ["git", "-C", str(БАЗА_ЗНАНИЙ), "reset", "--hard", "--quiet", "origin/HEAD"],
                check=True,
                timeout=120,
            )
        else:
            БАЗА_ЗНАНИЙ.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run(
                ["git", "clone", "--quiet", "--depth", "1", url, str(БАЗА_ЗНАНИЙ)],
                check=True,
                timeout=180,
            )
        sha = subprocess.run(
            ["git", "-C", str(БАЗА_ЗНАНИЙ), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            timeout=30,
        ).stdout.strip()
        файлов = len(list(БАЗА_ЗНАНИЙ.glob("*.md")))
        return f"база знаний {sha}, файлов: {файлов}"
    except subprocess.CalledProcessError as e:
        return f"⚠️ база знаний не обновилась: {e}"
    except subprocess.TimeoutExpired:
        return "⚠️ база знаний не обновилась: таймаут"


def дельта_чатов(каб: dict) -> dict | None:
    """Детерминированный предфильтр: какие чаты показывать агенту в полном прогоне.

    Включено Ириком 22.08.2026 ради расхода. Из ~187 чатов за полдня меняются
    10–20; остальные агент перечитывал, чтобы убедиться, что там пусто, — и
    это была основная часть счёта за прогон.

    Фильтр — обычный код, модель здесь не участвует. Чат попадает агенту,
    если верно хотя бы одно из трёх:
      · «новое»       — последнее сообщение свежее старта прошлого прогона
                        (любое: реплика клиента, системный триггер, ответ Ирика
                        с телефона — всё это повод посмотреть);
      · «клиент ждёт» — последнее содержательное слово в чате за клиентом,
                        любой давности. Страховка от пропусков: даже если
                        прошлый прогон упал, неотвеченный клиент не потеряется;
      · «очередь касаний» — последнее слово наше и лежит в окне каденции:
                        шаг 4 (касания молчащим) без этого списка ослеп бы,
                        молчащие по определению «не изменились».

    Ошибка любого рода — возврат None и полный прогон: фильтр экономит деньги,
    но не имеет права стоить пропущенного клиента. Выключатель: DELTA_MODE=off.
    """
    from интеграции.avito import Avito

    try:
        id_var, secret_var = каб["переменные"]
        avito = Avito(
            client_id=os.environ[id_var], client_secret=os.environ[secret_var]
        )
        # Качаем до исчерпания: список отсортирован по updated по убыванию,
        # и «клиент ждёт ответа» обещает страховку ЛЮБОЙ давности — обрыв
        # пагинации молча превратил бы это обещание в ложь (первый боевой
        # прогон 22.08: потолок 500 при базе больше пятисот, поймала серверная
        # сессия). Потолок 3000 — предохранитель от бесконечного цикла, а не
        # рабочая граница; упёрлись в него — честно помечаем срез.
        чаты: list[dict] = []
        срез = False
        for offset in range(0, 3000, 100):
            страница = avito.chats_list(limit=100, offset=offset)
            чаты.extend(страница)
            if len(страница) < 100:
                break
        else:
            срез = True
        avito.close()
        if not чаты:
            return None

        сейчас = datetime.now(МСК)
        # Старт прошлого прогона: расписание фиксированное — 9:30 и 18:30 МСК.
        # Берём порогом ближайший из них, случившийся хотя бы 2 часа назад:
        # для вечернего это сегодняшнее утро, для утреннего — вчерашний вечер.
        # Запас именно 2 часа, а не 10 минут: контейнер может стартовать с
        # задержкой, и прогон, начавшийся в 9:41, при малом запасе взял бы
        # порогом собственные 9:30 — «новое» стало бы пустым (замечание
        # серверной сессии 22.08).
        # Порог — СТАРТ прошлого прогона, а не конец: сообщения, пришедшие во
        # время его работы, попадут и в следующий прогон. Дубль разбора дешевле
        # пропуска, а правило «перечитай ветку» не даст ответить дважды.
        метки = []
        for дней in (0, 1):
            день = сейчас - timedelta(days=дней)
            for ч, м in ((9, 30), (18, 30)):
                метки.append(день.replace(hour=ч, minute=м, second=0, microsecond=0))
        порог = max(м for м in метки if м <= сейчас - timedelta(hours=2))

        # Окно очереди касаний: от минимального интервала каденции (с допуском
        # в полдня) до последнего шага плюс запас на браковку. Старше окна —
        # цепочка давно отработана или чат вне работы.
        каденция = каб.get("каденция") or (0, 2, 4, 7)
        окно_от = timedelta(days=1.5)
        окно_до = timedelta(days=max(каденция) + 4)

        выбрано: list[tuple[str, str, str]] = []
        for c in чаты:
            lm = c.get("last_message") or {}
            ts = lm.get("created") or 0
            когда = datetime.fromtimestamp(ts, МСК) if ts else None
            направление = lm.get("direction")
            тип = lm.get("type")
            возраст = сейчас - когда if когда else None

            if когда and когда >= порог:
                причина = "новое"
            elif направление == "in" and тип != "system":
                причина = "клиент ждёт ответа"
            elif (
                направление == "out"
                and возраст
                and окно_от <= возраст <= окно_до
                # Касания ведёт follow-up-раннер (правило Ирика 22.08.2026) —
                # очередь касаний прогону не показываем: он по ней всё равно
                # не пишет, а 150+ чатов очереди раздували дельту впустую.
                and not каб.get("касания_ведёт_раннер")
            ):
                причина = "очередь касаний"
            else:
                continue

            u = [x for x in c.get("users", []) if str(x.get("id")) != каб["avito_user_id"]]
            имя = (u[0].get("name") if u else "") or "без имени"
            выбрано.append((c["id"], имя, причина))

        # Сбой фильтра ловим только по «новое» + «клиент ждёт»: если свежих
        # событий больше 60% базы, вероятнее ошибка порога, чем реальный
        # всплеск. «Очередь касаний» в признак сбоя НЕ входит: это
        # предсказуемый объём работы, после массовой отправки она законно
        # велика. Замер серверной сессии 22.08 на реальном снимке: 34 чата
        # очереди + 40 новых дали 75% и ложное срабатывание — дельта глушила
        # себя ровно в те дни, когда экономия нужнее всего. И даже дельта в
        # 75 чатов экономит: агент не открывает остальную сотню.
        свежих = sum(1 for _, _, п in выбрано if п != "очередь касаний")
        if свежих > max(20, int(len(чаты) * 0.6)):
            return None

        return {"выбрано": выбрано, "всего": len(чаты), "порог": порог, "срез": срез}
    except Exception as e:
        print(f"дельта-фильтр недоступен ({type(e).__name__}: {e}) — полный прогон", flush=True)
        return None


def блок_дельты(дельта: dict | None) -> str:
    if дельта is None:
        return ""
    строки = "\n".join(
        f"  · {cid} — {имя} — {причина}" for cid, имя, причина in дельта["выбрано"]
    )
    # Бриф не имеет права утверждать больше, чем фильтр проверил: при срезе
    # пагинации фраза «это уже проверено» верна только для просмотренной части.
    оговорка_среза = (
        f"\n⚠️ Проверены первые {дельта['всего']} чатов по свежести обновления — "
        "дальше срез пагинации. Непросмотренный хвост не обновлялся дольше всех "
        "остальных; если ищешь конкретный старый чат — открой его напрямую.\n"
        if дельта.get("срез")
        else ""
    )
    if not дельта["выбрано"]:
        return (
            "\n\n⚡ ДЕЛЬТА-РЕЖИМ: с прошлого прогона "
            f"({дельта['порог']:%d.%m %H:%M} МСК) ни в одном из {дельта['всего']} чатов "
            "не было событий, никто не ждёт ответа и никому не пора касание.\n"
            "Чаты НЕ открывай и базу НЕ обходи. Быстро проверь задачи и хвосты в "
            "Битриксе, запиши короткий журнал и заверши прогон.\n"
        )
    return (
        "\n\n⚡ ДЕЛЬТА-РЕЖИМ (правило Ирика от 22.08.2026): предфильтр уже обошёл "
        f"все {дельта['всего']} чатов кабинета кодом. Работать есть смысл только в "
        f"этих {len(дельта['выбрано'])} — работай ТОЛЬКО с ними:\n{строки}\n"
        f"Остальные чаты НЕ открывай: с прошлого прогона ({дельта['порог']:%d.%m %H:%M} МСК) "
        "там ничего не произошло, никто не ждёт ответа и касание никому из них не "
        "по сроку — это уже проверено по датам и направлению последнего сообщения.\n"
        "«Очередь касаний» — кандидат по возрасту: пора ли касание по каденции и "
        "нет ли отказа — решай сам по ветке и Битриксу, как обычно.\n"
        "Сверку с Битриксом делай точечно по этим чатам; задачи и хвосты по сделкам "
        "вне списка делать можно. В отчёте укажи: «дельта: N из M чатов».\n"
        + оговорка_среза
    )


