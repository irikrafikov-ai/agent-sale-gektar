"""Точка входа сервиса: один прогон агента.

Запускается по расписанию Railway. Порядок:
  1. подтянуть свежую базу знаний из отдельного репозитория
  2. отдать агенту регламент и дать ему отработать цикл
  3. отправить отчёт в Телеграм и записать журнал

База знаний тянется перед каждым прогоном намеренно: Ирик правит её
напрямую, и копия в образе устарела бы в первый же день.
"""

from __future__ import annotations

import asyncio
import os
import subprocess
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

from claude_agent_sdk import ClaudeAgentOptions, query

sys.path.insert(0, str(Path(__file__).parent))

import инструменты  # noqa: E402
from интеграции.telegram import Telegram  # noqa: E402

КОРЕНЬ = Path(__file__).resolve().parent.parent
БАЗА_ЗНАНИЙ = Path(os.environ.get("KB_PATH", "/opt/база-знаний"))
МСК = timezone(timedelta(hours=3))


def обновить_базу_знаний() -> str:
    """Клонирует или обновляет репозиторий базы знаний. Возвращает статус для отчёта."""
    url = os.environ.get("KB_REPO_URL")
    if not url:
        return "⚠️ KB_REPO_URL не задан — база знаний недоступна"

    token = os.environ.get("KB_TOKEN")
    if token and url.startswith("https://"):
        url = url.replace("https://", f"https://x-access-token:{token}@", 1)

    try:
        if (БАЗА_ЗНАНИЙ / ".git").exists():
            subprocess.run(
                ["git", "-C", str(БАЗА_ЗНАНИЙ), "fetch", "--quiet", "origin"], check=True, timeout=120
            )
            subprocess.run(
                ["git", "-C", str(БАЗА_ЗНАНИЙ), "reset", "--hard", "--quiet", "origin/HEAD"],
                check=True,
                timeout=120,
            )
        else:
            БАЗА_ЗНАНИЙ.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run(
                ["git", "clone", "--quiet", "--depth", "1", url, str(БАЗА_ЗНАНИЙ)],
                check=True,
                timeout=180,
            )
        sha = subprocess.run(
            ["git", "-C", str(БАЗА_ЗНАНИЙ), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            timeout=30,
        ).stdout.strip()
        файлов = len(list(БАЗА_ЗНАНИЙ.glob("*.md")))
        return f"база знаний {sha}, файлов: {файлов}"
    except subprocess.CalledProcessError as e:
        return f"⚠️ база знаний не обновилась: {e}"
    except subprocess.TimeoutExpired:
        return "⚠️ база знаний не обновилась: таймаут"


def задание(вид: str, статус_базы: str) -> str:
    сейчас = datetime.now(МСК)
    режим = os.environ.get("AGENT_MODE", "send")

    предупреждение = (
        ""
        if режим == "send"
        else "\n⚠️ РЕЖИМ READ-ONLY: инструмент отправки клиентам заблокирован. "
        "Битрикс ведёшь как обычно, тексты сообщений включи в отчёт.\n"
    )

    return f"""Сейчас {сейчас.strftime('%d.%m.%Y %H:%M')} МСК, прогон: {вид}.
Ты работаешь автономно на сервере. Показывать тексты некому — отправляй сам,
в рамках регламента. Спорные случаи — стоп-краны, алерт через telegram_alert.
{предупреждение}
Состояние: {статус_базы}

ПОРЯДОК:
1. Прочитай {КОРЕНЬ}/AGENT.md — конституция, она отменяет всё остальное при конфликте.
2. Прочитай {КОРЕНЬ}/регламент/01-рабочий-цикл.md и иди по нему.
3. Продуктовую базу знаний читай из {БАЗА_ЗНАНИЙ} — там актуальные цены,
   скрипты, возражения, участки. Копий не делай.
4. Рабочая память — {КОРЕНЬ}/данные/реестр-клиентов.md, обнови её в конце.
5. Журнал прогона запиши в {КОРЕНЬ}/данные/журнал/{сейчас:%Y-%m-%d}-{вид}.md

ЗАВЕРШЕНИЕ: последним сообщением выдай отчёт по формату
{КОРЕНЬ}/регламент/04-отчёт.md. Он уйдёт Ирику в Телеграм как есть —
пиши его для человека, а не как лог. Раздел «Требует вас» ставь первым.
"""


def задание_чат(chat_id: str, повод: str, статус_базы: str) -> str:
    """Разбор одного чата — сюда агента будит вебхук.

    Отличие от полного прогона принципиальное: здесь не надо снимать картину по
    всей базе, не надо касаний и браковки. Клиент прямо сейчас в приложении,
    цена задержки — заявка. Один чат, один ход, минимум лишних шагов.
    """
    сейчас = datetime.now(МСК)
    режим = os.environ.get("AGENT_MODE", "send")

    предупреждение = (
        ""
        if режим == "send"
        else "\n⚠️ РЕЖИМ READ-ONLY: инструмент отправки клиентам заблокирован.\n"
    )

    return f"""Сейчас {сейчас.strftime('%d.%m.%Y %H:%M')} МСК. Это НЕ полный прогон.

Вебхук Авито разбудил тебя по одному чату: {chat_id}
Повод: {повод}
{предупреждение}
Состояние: {статус_базы}

ЗАДАЧА: сделать ровно один следующий ход по этому чату — и остановиться.
Картину по всей базе не снимай, касания и браковку не трогай, журнал не пиши.
Этим занимаются утренний и вечерний прогоны.

ПОРЯДОК:
1. Прочитай {КОРЕНЬ}/AGENT.md — конституция, она отменяет всё при конфликте.
2. Прочитай {КОРЕНЬ}/регламент/01-рабочий-цикл.md, шаг 2 — разбор ответившего чата.
   Пункт 0 обязателен: сверься с Битриксом ДО отправки. Стоит ОТКАЗ или
   ДУБЛЬ — не пишешь, даже если текст напрашивается сам.
3. Прочитай переписку целиком через avito_chat_messages, а не одно сообщение.
4. Продуктовую базу знаний читай из {БАЗА_ЗНАНИЙ}. Копий не делай.
5. Отправь ОДНО сообщение одним вызовом. Не разбивай текст на части: 15.08
   шаблон ушёл тремя сообщениями подряд, и в чате это выглядело как сбой.
6. Сразу после отправки — комментарий в таймлайн и стадия, по 02-битрикс.md.

ЗАВЕРШЕНИЕ: последним сообщением выдай 3–5 строк для Телеграма — кто клиент,
что он написал, что ты ответил и почему. Без шапки полного отчёта.
"""


async def прогон(вид: str, chat_id: str | None = None, повод: str = "") -> str:
    статус_базы = обновить_базу_знаний()

    options = ClaudeAgentOptions(
        model=os.environ.get("AGENT_MODEL", "claude-opus-5"),
        cwd=str(КОРЕНЬ),
        mcp_servers={"gektar": инструменты.сервер},
        allowed_tools=["Read", "Glob", "Grep", "Write", "Edit"] + инструменты.ИМЕНА,
        permission_mode="bypassPermissions",
        max_turns=int(os.environ.get("AGENT_MAX_TURNS", "200")),
        system_prompt={"type": "preset", "preset": "claude_code"},
    )

    текст_задания = (
        задание_чат(chat_id, повод, статус_базы)
        if chat_id
        else задание(вид, статус_базы)
    )

    последний = ""
    try:
        async for message in query(prompt=текст_задания, options=options):
            for block in getattr(message, "content", []) or []:
                if getattr(block, "type", None) == "text" and block.text.strip():
                    последний = block.text
    except Exception as e:
        # Обрыв в конце хода — не повод терять всё, что агент уже сделал.
        #
        # 16.08 прогон упал с «Claude Code returned an error result: success».
        # Формулировка бессмысленная не случайно: CLI прислал результат с
        # is_error=True, пустым списком errors и subtype «success», а SDK,
        # не найдя текста ошибки, подставил subtype. То есть CLI сообщил об
        # ошибке, не сказав какой, и вышел с ненулевым кодом. Так выглядит
        # падение уже ПОСЛЕ работы — например, когда контейнер убит по памяти.
        #
        # Опасность тут не в самом падении, а в тишине: сообщения клиентам
        # ушли, Битрикс записан, а отчёт не дошёл. Не зная этого, прогон
        # запускают заново — и рассылка уходит по второму разу.
        if не_потерянный := последний.strip():
            отправлено = len(инструменты.отправленные())
            return (
                f"{не_потерянный}\n\n---\n"
                f"⚠️ **Прогон оборвался после работы.** `{type(e).__name__}: {e}`\n\n"
                f"Отчёт выше собран до обрыва и, скорее всего, отражает "
                f"выполненную работу: отправлено сообщений — {отправлено}.\n"
                f"**Перед повторным запуском сверьтесь с Битриксом и чатами** — "
                f"иначе рассылка уйдёт второй раз."
            )
        raise
    return последний


def запасной_отчёт(отправлено: list[dict]) -> str:
    """Отчёт из фактов, когда агент не написал его словами.

    17.08 разбор по вебхуку закончился строкой «Прогон завершён, но отчёт пуст —
    проверьте логи», хотя сообщение клиенту ушло. Это худший вид отчёта: работа
    сделана, а Ирик о ней не знает и вынужден лезть в Railway.

    Список отправленного у нас есть всегда — инструмент пишет туда факт каждой
    отправки. Значит и молчать не о чем: показываем, что реально ушло.
    """
    if not отправлено:
        return (
            "Прогон завершён. Сообщений клиентам не отправлено, "
            "текстового отчёта агент не оставил.\n\n"
            "Это не обязательно ошибка: так выглядит прогон, где отвечать было некому. "
            "Если ожидали другого — логи в Railway."
        )

    строки = []
    for м in отправлено:
        текст = (м.get("text") or "").replace("\n", " ")
        строки.append(f"· чат `{м.get('chat_id')}` — {текст[:160]}")

    return (
        f"⚠️ Агент не оставил текстового отчёта, собрал его из фактов отправки.\n\n"
        f"**Отправлено сообщений: {len(отправлено)}**\n\n" + "\n".join(строки) + "\n\n"
        "Стадии и комментарии в Битриксе проверьте в карточках — здесь только чаты."
    )


ОБЯЗАТЕЛЬНЫЕ = {
    "ANTHROPIC_API_KEY": "ключ Anthropic (console.anthropic.com → API Keys)",
    "AVITO_CLIENT_ID": "Авито → Настройки → Клиенты и приложения",
    "AVITO_CLIENT_SECRET": "там же, рядом с client_id",
    "BITRIX_WEBHOOK": "Битрикс → Разработчикам → Входящий вебхук",
    "TELEGRAM_BOT_TOKEN": "@BotFather → /newbot",
    "TELEGRAM_CHAT_ID": "@userinfobot",
}


def проверить_переменные() -> list[str]:
    """Возвращает список недостающих переменных — все сразу, а не первую попавшуюся.

    Без этой проверки процесс падал сырым KeyError на первой же отсутствующей
    переменной: чинишь одну, деплоишь, узнаёшь про следующую.
    """
    return [имя for имя in ОБЯЗАТЕЛЬНЫЕ if not os.environ.get(имя)]


def main() -> int:
    # Два способа запуска:
    #   прогон.py утро | вечер          — полный цикл по расписанию
    #   прогон.py чат <chat_id> <повод> — один чат, будит вебхук
    вид = sys.argv[1] if len(sys.argv) > 1 else "вечер"
    chat_id = ""
    повод = ""
    if вид == "чат":
        if len(sys.argv) < 3:
            print("Нужен chat_id: прогон.py чат <chat_id> [повод]", file=sys.stderr)
            return 1
        chat_id = sys.argv[2]
        повод = " ".join(sys.argv[3:]) or "событие в чате"

    недостаёт = проверить_переменные()
    if недостаёт:
        print("НЕ ХВАТАЕТ ПЕРЕМЕННЫХ ОКРУЖЕНИЯ — прогон не начат.\n", file=sys.stderr)
        for имя in недостаёт:
            print(f"  {имя:22} — {ОБЯЗАТЕЛЬНЫЕ[имя]}", file=sys.stderr)
        print(
            "\nЗадайте их в Railway → сервис → Variables. Шаблон: сервис/.env.example",
            file=sys.stderr,
        )
        # Если Телеграм настроен, а отвалилось что-то другое — сообщаем туда:
        # иначе про нерабочий прогон никто не узнает до вечернего отчёта.
        if not {"TELEGRAM_BOT_TOKEN", "TELEGRAM_CHAT_ID"} & set(недостаёт):
            try:
                Telegram().send(
                    "Прогон не начат: не заданы переменные окружения — "
                    + ", ".join(недостаёт),
                    alert=True,
                )
            except Exception:
                pass  # алерт не критичен, сообщение уже в логах Railway
        return 1

    telegram = Telegram()

    try:
        отчёт = asyncio.run(прогон(вид, chat_id or None, повод))
    except Exception as e:
        # Алерт отправляем best-effort. Если Телеграм тоже недоступен, его
        # ошибка не должна подменять настоящую причину падения: иначе в логах
        # видно «TelegramError», а из-за чего упал прогон — уже нет.
        try:
            telegram.send(f"Прогон *{вид}* упал: `{type(e).__name__}: {e}`", alert=True)
        except Exception as ошибка_алерта:
            print(f"алерт в Телеграм не ушёл: {ошибка_алерта}", file=sys.stderr)
        raise

    отправлено = инструменты.отправленные()
    подпись = (
        f"\n\n---\n_Разбор по вебхуку, чат {chat_id}, отправлено: {len(отправлено)}_"
        if chat_id
        else f"\n\n---\n_Прогон {вид}, отправлено сообщений: {len(отправлено)}_"
    )
    шапка = "⚡️ *Ответ по вебхуку*\n\n" if chat_id else ""

    telegram.send(шапка + (отчёт.strip() or запасной_отчёт(отправлено)) + подпись)
    telegram.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
