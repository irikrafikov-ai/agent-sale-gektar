print("\n— 26.09: отправка в MAX/Телеграм отказала, причина названа человеческим языком")
# Живая попытка отправить фото тёплому клиенту: MAX ответил «session with
# connectionId … not found» (канал разлогинен), Телеграм — «CAN_NOT_GET_USER_
