проверь("выключенный кабинет не считается настроенным даже с ключами", not _реестр.настроен(_реестр.кабинет("dolina")))
проверь("активные — только Берега", _реестр.активные() == ["gektar"])
проверь("вебхук отбрасывает событие выключенного кабинета до задачи",
        'if каб.get("выключен"):' in (Path(__file__).parent / "вебхук.py").read_text())
проверь("отчёт считает только активные кабинеты",
        "реестр.активные()" in (Path(__file__).parent / "отчёт.py").read_text())

print("\n— 25.09: папка живых фото есть, видео в ней нет")
# Ирик дал ссылку 24.09 в ответ на долг по шести тёплым. Две ловушки:
