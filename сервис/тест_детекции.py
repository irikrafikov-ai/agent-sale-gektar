"""Проверка детекции вебхука на настоящих данных Авито, а не на выдуманных.

fastapi локально не стоит (и python здесь 3.9), поэтому подсовываем заглушки:
проверяем чистую логику решения, а не веб-слой.
"""

import sys
import types
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent

# --- заглушки -------------------------------------------------------------
fastapi = types.ModuleType("fastapi")


class _App:
    def __init__(self, **kw):
        pass

    def get(self, *a, **k):
        return lambda f: f

    def post(self, *a, **k):
        return lambda f: f


fastapi.FastAPI = _App
fastapi.Request = object
fastapi.Response = object
fastapi.BackgroundTasks = object
sys.modules["fastapi"] = fastapi

for имя in ("интеграции", "интеграции.avito", "интеграции.bitrix", "интеграции.telegram"):
    sys.modules.setdefault(имя, types.ModuleType(имя))
sys.modules["интеграции.avito"].Avito = object
sys.modules["интеграции.avito"].AvitoError = Exception
sys.modules["интеграции.bitrix"].Bitrix = object
sys.modules["интеграции.telegram"].Telegram = object

sys.path.insert(0, str(КОРЕНЬ / "сервис"))
import вебхук  # noqa: E402

НАШ = 84069402

# --- настоящие сообщения из чата u2i-WoR14xy3xcFubOv_ZOiPuA ---------------
ТРИГГЕР = {
    "id": "14910e89b862b1b920bbef181bfd1467",
    "author_id": 1,
    "content": {
        "text": "[Системное сообщение] Пользователь ознакомился с вашим предложением: "
        "специальные условия на покупку земельного участка , но ещё не дал ответа. "
        "Напишите в чат, чтобы обсудить детали.",
        "flow_id": "flower_499469",
    },
    "type": "system",
    "direction": "in",
}
НАШ_ШАБЛОН = {
    "id": "414c212272a92c66d21526b189727b0e",
    "author_id": НАШ,
    "content": {"text": "Добрый день 🙂\n\n Вы смотрели спецусловия... "
                        "https://partners.gektar.expert/tour/kostomarovo/ ..."},
    "type": "text",
    "direction": "out",
}
КЛИЕНТ_ПИШЕТ = {
    "id": "aaa",
    "author_id": 12345,
    "content": {"text": "А свет подведён к участку?"},
    "type": "text",
    "direction": "in",
}
ДРУГОЕ_СИСТЕМНОЕ = {
    "id": "bbb",
    "author_id": 1,
    "content": {"text": "[Системное сообщение] Пользователь оставил отзыв."},
    "type": "system",
    "direction": "in",
}

провалов = 0


def проверить(что, получено, ожидалось):
    global провалов
    ок = получено == ожидалось
    провалов += not ок
    print(f"  {'✅' if ок else '❌'} {что}: {получено!r} (ждали {ожидалось!r})")


print("1. Распознавание триггера в НАСТОЯЩЕМ тексте Авито")
тело = вебхук.текст(ТРИГГЕР).lower()
проверить("триггер найден", any(т in тело for т in вебхук.ТРИГГЕРЫ), True)
проверить("направление — входящее", вебхук.исходящее(ТРИГГЕР, НАШ), False)
проверить("тип системный", ТРИГГЕР.get("type") == "system", True)

print("\n2. Своё сообщение не принимаем за клиентское (защита от петли)")
проверить("наш шаблон — исходящий", вебхук.исходящее(НАШ_ШАБЛОН, НАШ), True)
проверить("сообщение клиента — входящее", вебхук.исходящее(КЛИЕНТ_ПИШЕТ, НАШ), False)

print("\n3. След шаблона в истории")
проверить("шаблон опознан по ссылке", вебхук.СЛЕД_ШАБЛОНА in вебхук.текст(НАШ_ШАБЛОН), True)
проверить("в тексте клиента следа нет", вебхук.СЛЕД_ШАБЛОНА in вебхук.текст(КЛИЕНТ_ПИШЕТ), False)

print("\n4. Прочие системные сообщения не будят агента")
чужое = вебхук.текст(ДРУГОЕ_СИСТЕМНОЕ).lower()
проверить("не триггер", any(т in чужое for т in вебхук.ТРИГГЕРЫ), False)

print("\n5. Две другие формулировки Авито")
for ф in (
    "Пользователь выразил готовность к покупке, но не дал окончательного ответа.",
    "Покупателя заинтересовало ваше предложение.",
):
    проверить(f"«{ф[:38]}…»", any(т in ф.lower() for т in вебхук.ТРИГГЕРЫ), True)

print("\n6. chat_id достаётся из любой вложенности payload")
проверить(
    "форма v3 (payload.value.chat_id)",
    вебхук.найти_chat_id(
        {"id": "x", "payload": {"type": "message", "value": {"chat_id": "u2i-ABC", "id": "m1"}}}
    ),
    "u2i-ABC",
)
проверить("плоская форма", вебхук.найти_chat_id({"chat_id": "u2i-FLAT"}), "u2i-FLAT")
проверить("camelCase", вебхук.найти_chat_id({"a": [{"chatId": "u2i-CAMEL"}]}), "u2i-CAMEL")
проверить("нет вовсе", вебхук.найти_chat_id({"foo": "bar"}), None)

print("\n7. Шаблон — ровно тот, что утверждён")
проверить("цена акции 265 000", "265 000 ₽" in вебхук.ШАБЛОН, True)
проверить("зачёркнутая 295 000", "295 000 ₽" in вебхук.ШАБЛОН, True)
проверить("закрывающий вопрос на месте", вебхук.ШАБЛОН.rstrip().endswith("участок или платежи?"), True)
проверить("одно сообщение, не три", вебхук.ШАБЛОН.count("https://") == 1, True)

print(f"\n{'ВСЁ ЗЕЛЁНОЕ' if not провалов else f'ПРОВАЛОВ: {провалов}'}")
sys.exit(1 if провалов else 0)
