"""Проверка арифметики молчунов на тех случаях, где ошиблась модель.

Каждая проверка ниже — реальная ошибка ручного подсчёта от 01.09.2026,
а не выдуманный сценарий.
"""

import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

for имя in ("интеграции", "интеграции.avito", "интеграции.bitrix", "интеграции.telegram"):
    sys.modules.setdefault(имя, types.ModuleType(имя))
sys.modules["интеграции.avito"].Avito = object
sys.modules["интеграции.avito"].AvitoError = Exception
sys.modules["интеграции.bitrix"].Bitrix = object
sys.modules["интеграции.telegram"].Telegram = object

import молчуны  # noqa: E402

провалов = 0


def проверить(что, получили, ждали):
    global провалов
    ок = получили == ждали
    провалов += 0 if ок else 1
    print(f"  {'✅' if ок else '❌'} {что}: {получили!r} (ждали {ждали!r})")


НАШ = 84069402
# 12:00 01.09.2026 МСК и сутки назад — точные метки не важны, важен порядок
ПОЗЖЕ, РАНЬШЕ = 1788255000, 1788168600


def наше(t=ПОЗЖЕ):
    return {"direction": "out", "author_id": НАШ, "created": t, "type": "text"}


def клиента(t=ПОЗЖЕ):
    return {"direction": "in", "author_id": 555, "created": t, "type": "text"}


def служебное(t=ПОЗЖЕ):
    return {"direction": "in", "author_id": 1, "created": t, "type": "system"}


print("1. Служебные уведомления Авито не считаются касаниями")
# Ровно эта ошибка завысила касания вдвое-втрое: у Aleksa 5 наших превратились
# в 19, у Инны Андреевны 7 — в 15.
история = [наше(), наше(), служебное(), служебное(), служебное()]
свод = молчуны.разобрать_чат(история, НАШ)
проверить("наших ровно два", свод["наши"], 2)
проверить("служебные не ушли в клиентские", свод["клиента"], 0)
проверить("служебное опознано", молчуны.системное(служебное()), True)
проверить("наше не считается служебным", молчуны.системное(наше()), False)

print("\n2. Ответы клиента не теряются")
# У Дмитрия пять живых ответов пропали, и он попал в «ни разу не ответил».
история = [наше(), клиента(РАНЬШЕ), наше(), клиента(РАНЬШЕ), служебное()]
свод = молчуны.разобрать_чат(история, НАШ)
проверить("клиентских два", свод["клиента"], 2)
проверить("наших два", свод["наши"], 2)

print("\n3. Молчун — это ноль ответов, а не «давно не писал»")
только_наши = [наше() for _ in range(14)]  # случай Карины
свод = молчуны.разобрать_чат(только_наши, НАШ)
проверить("касаний четырнадцать", свод["наши"], 14)
проверить("ответов ноль", свод["клиента"], 0)
проверить("порог 7 пройден", свод["наши"] >= молчуны.ПОРОГ, True)

шесть = [наше() for _ in range(6)]
проверить(
    "шесть касаний — ещё не молчун",
    молчуны.разобрать_чат(шесть, НАШ)["наши"] >= молчуны.ПОРОГ,
    False,
)

print("\n4. Направление важнее author_id")
# У системных сообщений author_id равен 1, а не id клиента — на этом
# основана путаница в ручном подсчёте.
без_направления = {"author_id": НАШ, "created": ПОЗЖЕ, "type": "text"}
проверить("наше по author_id, если нет direction", молчуны.наше(без_направления, НАШ), True)
чужое = {"author_id": 555, "created": ПОЗЖЕ, "type": "text"}
проверить("чужое по author_id", молчуны.наше(чужое, НАШ), False)

print("\n5. Даты берутся по последнему сообщению каждой стороны")
свод = молчуны.разобрать_чат([наше(ПОЗЖЕ), наше(РАНЬШЕ), клиента(РАНЬШЕ)], НАШ)
проверить("дата нашего последнего — самая поздняя", свод["наше_последнее"], "01.09.2026")
проверить("дата клиента — его собственная", свод["клиент_последний"], "31.08.2026")
проверить("пустая история не ломает разбор", молчуны.разобрать_чат([], НАШ)["наши"], 0)
проверить("без сообщений дата пустая", молчуны.разобрать_чат([], НАШ)["наше_последнее"], "")

print("\n6. Имя собеседника — не наше")
чат = {"users": [{"id": НАШ, "name": "«Щекинские берега»"}, {"id": 555, "name": "Карина"}]}
проверить("взято имя клиента", молчуны.имя_собеседника(чат, НАШ), "Карина")
проверить("без участников — пусто", молчуны.имя_собеседника({}, НАШ), "")

print("\n7. История читается целиком, а не первой страницей")


class _Клиент:
    """Отдаёт 250 сообщений по 100 за раз — как настоящий API."""

    def __init__(self):
        self.запросов = 0

    def chat_messages(self, chat_id, limit=100, offset=0):
        self.запросов += 1
        всего = 250
        if offset >= всего:
            return []
        return [наше() for _ in range(min(limit, всего - offset))]


к = _Клиент()
проверить("собрано всё", len(молчуны.все_сообщения(к, "u2i-X")), 250)
проверить("страниц запрошено три", к.запросов, 3)

print("\n8. Дешёвый отсев: кто отвечал — того не читаем")
проверить(
    "последнее слово клиента — не молчун",
    молчуны.клиент_уже_писал({"last_message": клиента()}),
    True,
)
проверить(
    "последнее слово наше — надо смотреть историю",
    молчуны.клиент_уже_писал({"last_message": наше()}),
    False,
)
проверить(
    "служебное входящее не считается ответом клиента",
    молчуны.клиент_уже_писал({"last_message": служебное()}),
    False,
)
проверить("пустой чат не отсеивается", молчуны.клиент_уже_писал({}), False)

print("\n9. Ревизия встроена в вечерний прогон")
исходник = (Path(__file__).parent / "прогон.py").read_text(encoding="utf-8")
проверить("прогон импортирует молчунов", "import молчуны" in исходник, True)
проверить("ревизия только вечером", 'если вид == "вечер"' in исходник
          or 'вид == "вечер" and not chat_id' in исходник, True)
проверить("находки закрываются", "молчуны.забраковать(находки)" in исходник, True)
проверить("блок попадает в отчёт", "блок_молчунов + подпись" in исходник, True)
проверить("сбой ревизии не роняет отчёт", "Ревизия молчунов не отработала" in исходник, True)

print(f"\n{'ВСЁ ЗЕЛЁНОЕ' if not провалов else f'ПРОВАЛОВ: {провалов}'}")
sys.exit(1 if провалов else 0)
