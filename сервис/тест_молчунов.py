print("\n11. Открытая линия Битрикса — параллельный коннектор к тем же чатам")
# 06.09 вручную нашлось и разобрано 69 карточек «… — Открытая линия»:
# площадка заводит свою пару лид+сделка на каждое сообщение Авито (оба
# кабинета, комментарий про то, что Долина не подключена, — устарел), а наш
# код не знает об этом и заводит карточки тем же чатам отдельно. Без
# автоматики это копится заново каждый день.


class _ФейкБитриксЛинии:
    def __init__(self, сделки_линии=(), лиды=None, первичные=()):
        self.сделки_линии = list(сделки_линии)
        self.лиды = лиды or {}
        self.первичные = list(первичные)
        self.апдейты: list[tuple] = []
        self.комментарии: list[tuple] = []
        self.добавления: list[tuple] = []

    def crm_list(self, entity, filter=None, select=None, limit=50):
        if entity != "deal":
            return []
        if filter and "%ORIGIN_ID" in filter:
            return self.первичные
        if filter and "%TITLE" in filter:
            return self.сделки_линии
        if filter and "ORIGIN_ID" in filter:
            return []  # «своя» карточка по точному chat_id — в этих тестах её нет
        return []

    def crm_get(self, entity, id):
        if entity != "lead":
            raise AssertionError(f"неожиданная сущность {entity}")
        return self.лиды[str(id)]

    def crm_update(self, entity, id, fields):
        self.апдейты.append((id, fields))
        return True

    def crm_add(self, entity, fields):
        ид = 9000 + len(self.добавления)
        self.добавления.append((ид, fields))
        return ид

    def timeline_comment_add(self, deal_id, comment):
        self.комментарии.append((deal_id, comment))
        return 1

    def close(self):
        pass


