"""Журнал обучения агента — уроки и гипотезы, которые переживают деплой.

Требование Ирика 18.09.2026: агент обязан каждый день глубоко разбирать
свою работу, проверять гипотезы и учиться, чтобы конверсия из заявки в
продажу росла. Размышление, которое никто потом не читает, ничему не учит.
Поэтому вывод дня не просто печатается в отчёт, а оставляет след:

  · УРОК — что понял сегодня и как теперь делаю (короткое правило);
  · ГИПОТЕЗА — что проверяю, как именно и по какой цифре пойму результат.

Утренний прогон и каждый разбор чата ЧИТАЮТ этот журнал и применяют
действующие уроки и гипотезы, а вечерний прогон — сверяет гипотезы с
цифрами дня и закрывает их: подтверждена / опровергнута / снята.

Хранилище — таймлайн служебной карточки Битрикса (сделка 3397), по той же
причине, что и журнал расхода: контейнеры агента общей памяти не имеют,
а Битрикс доступен всем и переживает передеплой. Формат строк машинный:

    УРОК|<unix>|<текст>
    ГИПОТЕЗА|<unix>|<№>|<статус>|<формулировка>|<как проверяем>|<метрика>

Статусы гипотезы: проверяю · подтверждена · опровергнута · снята.
Запись никогда не роняет прогон: не удалось — строка в stderr, работа идёт.
"""

from __future__ import annotations

import os
import re
import sys
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from интеграции.bitrix import Bitrix  # noqa: E402

МСК = timezone(timedelta(hours=3))

СДЕЛКА_ОБУЧЕНИЯ = os.environ.get("СДЕЛКА_ЖУРНАЛА_ОБУЧЕНИЯ", "3397")

# Сколько дней урок считается действующим в брифе. Старше — остаётся в
# журнале для недельного разбора, но в каждый чат уже не подмешивается:
# бриф должен быть коротким, а правило, прожившее две недели, либо уже
# вошло в регламент, либо не стоило того.
ДНЕЙ_УРОК_В_БРИФЕ = int(os.environ.get("ДНЕЙ_УРОК_В_БРИФЕ", "14"))
МАКС_УРОКОВ_В_БРИФЕ = 7
МАКС_ГИПОТЕЗ = 3  # больше трёх одновременно — ни одна не проверится честно

СТАТУСЫ = ("проверяю", "подтверждена", "опровергнута", "снята")


def _чисто(т: str) -> str:
    """Одна строка без разделителя формата."""
    return " ".join(str(т or "").replace("|", "/").split())


# --- разбор строк журнала ----------------------------------------------------


def разобрать(текст: str) -> dict | None:
    т = (текст or "").strip()
    if т.startswith("УРОК|"):
        ч = т.split("|", 2)
        if len(ч) < 3:
            return None
        try:
            return {"вид": "урок", "когда": float(ч[1]), "текст": ч[2].strip()}
        except ValueError:
            return None
    if т.startswith("ГИПОТЕЗА|"):
        ч = т.split("|", 6)
        if len(ч) < 7:
            return None
        try:
            return {
                "вид": "гипотеза",
                "когда": float(ч[1]),
                "номер": int(ч[2]),
                "статус": ч[3].strip(),
                "текст": ч[4].strip(),
                "проверка": ч[5].strip(),
                "метрика": ч[6].strip(),
            }
        except ValueError:
            return None
    return None


def _комментарии(b: Bitrix, предел: int = 600) -> list[dict]:
    собранные: list[dict] = []
    старт = 0
    while len(собранные) < предел:
        порция = b.call(
            "crm.timeline.comment.list",
            {
                "filter": {"ENTITY_ID": int(СДЕЛКА_ОБУЧЕНИЯ), "ENTITY_TYPE": "deal"},
                "order": {"ID": "DESC"},
                "start": старт,
            },
        ) or []
        собранные.extend(порция)
        if len(порция) < 50:
            break
        старт += 50
    return собранные


def прочитать(дней: int = 30) -> dict:
    """Журнал за период: уроки (новые первыми) и гипотезы в последнем статусе.

    У гипотезы может быть несколько строк (открыли → закрыли) — берём
    последнюю по времени для каждого номера.
    """
    порог = time.time() - дней * 86400
    уроки: list[dict] = []
    гипотезы: dict[int, dict] = {}
    b = None
    try:
        b = Bitrix()
        for к in _комментарии(b):
            з = разобрать(к.get("COMMENT") or "")
            if not з or з["когда"] < порог:
                continue
            if з["вид"] == "урок":
                уроки.append(з)
            elif з["номер"] not in гипотезы or гипотезы[з["номер"]]["когда"] < з["когда"]:
                гипотезы[з["номер"]] = з
    except Exception as ошибка:  # noqa: BLE001 — бриф без уроков лучше, чем без чата
        print(f"[обучение] журнал не прочитан: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass
    return {"уроки": уроки, "гипотезы": sorted(гипотезы.values(), key=lambda г: г["номер"])}


# --- запись ------------------------------------------------------------------


def _дописать(строки: list[str]) -> int:
    записано = 0
    b = None
    try:
        b = Bitrix()
        for с in строки:
            b.timeline_comment_add(СДЕЛКА_ОБУЧЕНИЯ, с)
            записано += 1
    except Exception as ошибка:  # noqa: BLE001
        print(f"[обучение] не записано: {type(ошибка).__name__}: {ошибка}", file=sys.stderr)
    finally:
        if b is not None:
            try:
                b.close()
            except Exception:  # noqa: BLE001
                pass
    return записано


def строка_урока(текст: str, когда: float | None = None) -> str:
    return f"УРОК|{int(когда or time.time())}|{_чисто(текст)}"


def строка_гипотезы(
    номер: int, статус: str, текст: str, проверка: str, метрика: str, когда: float | None = None
) -> str:
    if статус not in СТАТУСЫ:
        статус = "проверяю"
    return (
        f"ГИПОТЕЗА|{int(когда or time.time())}|{int(номер)}|{статус}|"
        f"{_чисто(текст)}|{_чисто(проверка)}|{_чисто(метрика)}"
    )


# --- вытаскиваем уроки и гипотезы из текста вывода дня -----------------------

_УРОК = re.compile(r"^\s*#УРОК\s+(.+?)\s*$", re.M)
# #ГИПОТЕЗА <№> <статус>: <формулировка> | как проверяем | метрика
_ГИПОТЕЗА = re.compile(
    r"^\s*#ГИПОТЕЗА\s+(\d+)\s+(проверяю|подтверждена|опровергнута|снята)\s*:\s*(.+?)\s*$",
    re.M | re.I,
)


def из_вывода(текст: str, известные: list[dict] | None = None) -> dict:
    """Разобрать хвост вывода дня на уроки и гипотезы.

    Модель пишет их в конце вывода помеченными строками — код их находит и
    кладёт в журнал. Так вывод дня становится действием, а не сочинением.
    Для гипотезы без номера или с номером, которого нет, выдаём следующий
    свободный, чтобы модель не могла случайно затереть чужую.
    """
    занятые = {г["номер"] for г in (известные or [])}
    следующий = (max(занятые) + 1) if занятые else 1

    уроки = [_чисто(м.group(1)) for м in _УРОК.finditer(текст or "")]
    гипотезы: list[dict] = []
    for м in _ГИПОТЕЗА.finditer(текст or ""):
        номер = int(м.group(1))
        статус = м.group(2).lower()
        части = [ч.strip() for ч in м.group(3).split("|")]
        формулировка = части[0] if части else ""
        проверка = части[1] if len(части) > 1 else ""
        метрика = части[2] if len(части) > 2 else ""
        if not формулировка:
            continue
        if статус == "проверяю" and номер not in занятые:
            номер = следующий
            следующий += 1
            занятые.add(номер)
        гипотезы.append(
            {"номер": номер, "статус": статус, "текст": формулировка,
             "проверка": проверка, "метрика": метрика}
        )
    return {"уроки": уроки[:5], "гипотезы": гипотезы[:МАКС_ГИПОТЕЗ + 3]}


def сохранить_из_вывода(текст: str) -> dict:
    """Найти в выводе дня уроки и гипотезы и записать их в журнал."""
    было = прочитать(дней=60)
    найдено = из_вывода(текст, было["гипотезы"])
    строки = [строка_урока(у) for у in найдено["уроки"]]
    строки += [
        строка_гипотезы(г["номер"], г["статус"], г["текст"], г["проверка"], г["метрика"])
        for г in найдено["гипотезы"]
    ]
    записано = _дописать(строки) if строки else 0
    return {**найдено, "записано": записано}


# --- текст для брифов и для вывода дня ---------------------------------------


def для_брифа(журнал: dict | None = None) -> str:
    """Короткий блок в бриф чата и прогона: что применяю сегодня.

    Пустой журнал — пустая строка: бриф не должен нести заголовок без тела.
    """
    ж = журнал if журнал is not None else прочитать(дней=ДНЕЙ_УРОК_В_БРИФЕ)
    активные = [г for г in ж["гипотезы"] if г["статус"] == "проверяю"][:МАКС_ГИПОТЕЗ]
    уроки = ж["уроки"][:МАКС_УРОКОВ_В_БРИФЕ]
    if not активные and not уроки:
        return ""
    строки = ["\nЧЕМУ Я НАУЧИЛСЯ И ЧТО ПРОВЕРЯЮ (журнал обучения, применять в этом чате):"]
    for у in уроки:
        строки.append(f"  · урок {datetime.fromtimestamp(у['когда'], МСК):%d.%m}: {у['текст']}")
    for г in активные:
        строки.append(
            f"  · гипотеза №{г['номер']} (проверяю): {г['текст']}"
            + (f" — делаю так: {г['проверка']}" if г["проверка"] else "")
        )
    return "\n".join(строки) + "\n"


def для_вывода(журнал: dict | None = None) -> str:
    """Полный журнал для вечернего разбора: все гипотезы со статусами и уроки."""
    ж = журнал if журнал is not None else прочитать(дней=30)
    строки: list[str] = []
    # Экономия токенов (Ирик 18.09): в разбор идут гипотезы «проверяю» и
    # закрытые за последнюю неделю; давно закрытые — только в журнале.
    неделя = time.time() - 7 * 86400
    гипотезы = [г for г in ж["гипотезы"] if г["статус"] == "проверяю" or г["когда"] >= неделя]
    if гипотезы:
        строки.append("Гипотезы (последний статус):")
        for г in гипотезы:
            строки.append(
                f"  №{г['номер']} [{г['статус']}] {г['текст']}"
                + (f" · проверка: {г['проверка']}" if г["проверка"] else "")
                + (f" · метрика: {г['метрика']}" if г["метрика"] else "")
                + f" · {datetime.fromtimestamp(г['когда'], МСК):%d.%m}"
            )
    else:
        строки.append("Гипотез в журнале нет — сегодня заводится первая.")
    if ж["уроки"]:
        строки.append("Уроки прошлых дней (новые первыми):")
        for у in ж["уроки"][:7]:
            строки.append(f"  · {datetime.fromtimestamp(у['когда'], МСК):%d.%m}: {у['текст']}")
    else:
        строки.append("Уроков в журнале пока нет.")
    return "\n".join(строки)
