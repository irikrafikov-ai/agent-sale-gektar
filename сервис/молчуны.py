# ── Попросившие больше не писать ────────────────────────────────────────────
#
# Правило Ирика от 06.09.2026: «те кто просит больше им не пиши и в битриксе
# заброкуй». Повод — Анна: 28.08 она попросила не писать, мы согласились,
# и всё равно написали ей 02.09 и 04.09. Тогда она попросила второй раз.
#
# Живой стоп-кран в вебхуке ловит просьбу в момент отправки. Эта ревизия
# нужна для тех, кто попросил РАНЬШЕ, чем кран появился: их карточки в
# Битриксе до сих пор открыты, и ночной дожим до них дотянется.
#
# Читаем ОДНУ страницу истории (Авито отдаёт свежие сообщения первыми):
# просьба не писать по смыслу лежит в конце разговора, а сплошной проход
# по всем страницам всех чатов упирается в 503.


def найти_просивших(ключ: str, страница: int = 100) -> list[dict]:
    """Чаты, где клиент прямым текстом просил больше ему не писать."""
    каб = реестр.кабинет(ключ)
    if not реестр.настроен(каб):
        print(f"[{ключ}] не настроен — пропускаю", flush=True)
        return []

    id_, secret = каб["переменные"]
    клиент = Avito(client_id=os.environ[id_], client_secret=os.environ[secret])
    находки: list[dict] = []
    try:
        наш_id = клиент.user_id
        чаты: list[dict] = []
        сдвиг = 0
        while True:
            порция = клиент.chats_list(limit=100, offset=сдвиг)
            чаты.extend(порция)
            if len(порция) < 100:
                break
            сдвиг += 100

        print(f"[{ключ}] чатов всего: {len(чаты)}", flush=True)
        for чат in чаты:
            chat_id = чат.get("id")
            if not chat_id:
                continue
            # Отсева здесь нет намеренно. Напрашивается пропускать чаты, где
            # последнее слово за нами, — но именно так выглядит чат Анны:
            # она попросила не писать 04.09 в 20:46, а последним сообщением
            # стал наш ответ. Просьба лежит в глубине разговора, и увидеть её
            # можно только прочитав страницу.
            time.sleep(ПАУЗА)
            try:
                сообщения = клиент.chat_messages(chat_id, limit=страница)
            except Exception as ошибка:  # noqa: BLE001 — один чат не роняет ревизию
                print(f"[{ключ}] {chat_id}: не прочитался — {ошибка}", flush=True)
                continue
            просьба = просил_не_писать(сообщения, наш_id)
            if not просьба:
                continue
            находки.append(
                {
                    "chat_id": chat_id,
                    "кабинет": ключ,
                    "название": каб["название"],
                    "имя": имя_собеседника(чат, наш_id),
                    "цитата": ((просьба.get("content") or {}).get("text") or "").strip()[:200],
                    "когда": datetime.fromtimestamp(
                        просьба.get("created", 0), МСК
                    ).strftime("%d.%m.%Y %H:%M"),
                }
            )
    finally:
        клиент.close()
    return находки


def закрыть_просивших(находки: list[dict], открытые_линии: dict[str, dict] | None = None) -> None:
    """Закрыть в Битриксе с причиной «не интересно» и пометкой НЕ ПИСАТЬ.

    Пометка в названии — не украшение: вебхук принимает по ней решение
    молчать даже на новую заявку от этого человека. Поэтому текст пометки
    менять нельзя, а карточку обязательно привязывать к чату через
    ORIGIN_ID — по имени запрет применять нельзя, 05.09 совпадение имени
    уже заглушило постороннюю Татьяну на целую ночь.
    """
    b = Bitrix()
    try:
        for н in находки:
            подпись = (
                f"Ревизия просьб не писать {datetime.now(МСК):%d.%m.%Y}. "
                f"Чат {н['chat_id']}, {н['название']}. "
                f"Клиент попросил не писать {н['когда']}: «{н['цитата']}». "
                f"Ответы по этому чату заблокированы."
            )
            свои = b.crm_list(
                "deal",
                filter={"ORIGIN_ID": н["chat_id"]},
                select=["ID", "TITLE"],
                limit=1,
            )
            if свои:
                название = свои[0].get("TITLE") or "Без имени"
                if "НЕ ПИСАТЬ" not in название.upper():
                    название = f"{название} — ПРОСИЛ НЕ ПИСАТЬ"
                b.crm_update(
                    "deal",
                    свои[0]["ID"],
                    {
                        "TITLE": название,
                        "STAGE_ID": "LOSE",
                        "UF_CRM_FAIL_REASON": ПРИЧИНА_ОТКАЗ,
                    },
                )
                b.timeline_comment_add(свои[0]["ID"], подпись)
                print(f"  сделка {свои[0]['ID']} закрыта — {н['имя']}", flush=True)
                continue

            ид, была_линией = _привязать_или_создать(
                b,
                chat_id=н["chat_id"],
                поля={
                    "TITLE": f"{н['имя'] or 'Без имени'} (Авито) — ПРОСИЛ НЕ ПИСАТЬ",
                    "STAGE_ID": "LOSE",
                    "UF_CRM_FAIL_REASON": ПРИЧИНА_ОТКАЗ,
                },
                комментарий=подпись,
                открытые_линии=открытые_линии,
            )
            метка = "привязана открытая линия" if была_линией else "заведена закрытая сделка"
            print(f"  {метка} {ид} — {н['имя']}", flush=True)
    finally:
        b.close()


def main() -> int:
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    закрывать = "--закрыть" in sys.argv

    порог = int(аргументы[0]) if аргументы else ПОРОГ
    ключи = [аргументы[1]] if len(аргументы) > 1 else list(реестр.КАБИНЕТЫ)

    все: list[dict] = []
    for ключ in ключи:
        все.extend(найти(ключ, порог))

    print(f"\nМОЛЧУНЫ (касаний ≥ {порог}, ответов ноль): {len(все)}\n", flush=True)
    for н in sorted(все, key=lambda x: -x["наши"]):
        print(
            f"  {н['наши']:3} касаний · {н['имя'][:28]:30} · {н['название'][:18]:20}"
            f" · последнее {н['наше_последнее']} · {н['chat_id']}",
            flush=True,
        )

    if закрывать and все:
        print("\nЗакрываю в Битриксе:", flush=True)
        забраковать(все)
    elif все:
        print("\nЧтобы забраковать их в Битриксе, добавь --закрыть", flush=True)
    return 0


