"""Молчуны: кому мы написали N раз и кто не ответил ни разу.

Почему это код, а не работа модели. 01.09.2026 такую ревизию пробовали
сделать чтением историй через модель — три прохода подряд дали три разных
ответа. Служебные уведомления Авито («создал чат», «посмотрел номер»)
считались нашими сообщениями и завышали касания вдвое-втрое; у Карины
14 касаний превратились в 6, а живой клиент с пятью ответами угодил в
«ни разу не ответил». По таким данным закрывать лида нельзя: цена ошибки —
либо брошенный живой человек, либо токены, которые жгутся дальше.

Арифметика должна быть арифметикой. Здесь она пересчитывается по полю
`direction` из ответа API — тому же признаку, на котором стоит вебхук.

Запуск:
    python сервис/молчуны.py                # оба кабинета, порог 7, только показать
    python сервис/молчуны.py 5              # порог 5
    python сервис/молчуны.py 7 gektar       # один кабинет
    python сервис/молчуны.py 7 gektar --закрыть   # ещё и забраковать в Битриксе
"""

from __future__ import annotations

import os
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).parent))

from интеграции.avito import Avito  # noqa: E402
from интеграции.bitrix import Bitrix  # noqa: E402

import кабинеты as реестр  # noqa: E402

МСК = timezone(timedelta(hours=3))

# Причина «Не отвечает (после дожима)» в справочнике UF_CRM_FAIL_REASON.
ПРИЧИНА_МОЛЧАНИЕ = "55"

# Сколько касаний считаем исчерпанным дожимом. Значение Ирика от 01.09.2026.
ПОРОГ = 7


def системное(сообщение: dict) -> bool:
    """Уведомление Авито, а не живая реплика.

    Именно на этом сломался ручной подсчёт: «Пользователь создал чат» и
    «посмотрел номер» приходят в общей ленте, и их легко принять за наши.
    """
    if сообщение.get("type") == "system":
        return True
    return str(сообщение.get("author_id")) in ("0", "1")


def наше(сообщение: dict, наш_id: int) -> bool:
    """Наша реплика. `direction` надёжнее author_id — см. вебхук.исходящее."""
    направление = сообщение.get("direction")
    if направление in ("out", "in"):
        return направление == "out"
    return str(сообщение.get("author_id")) == str(наш_id)


def все_сообщения(клиент: Avito, chat_id: str, предел: int = 400) -> list[dict]:
    """Вся история чата, а не первая страница.

    Ограничение в 50–60 сообщений съедало длинные переписки, а именно они
    и есть кандидаты в молчуны: у Карины было 14 касаний, у иных больше.
    """
    собрано: list[dict] = []
    сдвиг = 0
    while len(собрано) < предел:
        порция = клиент.chat_messages(chat_id, limit=100, offset=сдвиг)
        if not порция:
            break
        собрано.extend(порция)
        if len(порция) < 100:
            break
        сдвиг += 100
    return собрано


def разобрать_чат(сообщения: list[dict], наш_id: int) -> dict:
    """Сводка по одному чату: сколько наших, сколько клиента, когда."""
    наши = [с for с in сообщения if not системное(с) and наше(с, наш_id)]
    клиентские = [с for с in сообщения if not системное(с) and not наше(с, наш_id)]

    def когда(пачка: list[dict]) -> str:
        метки = [с.get("created") for с in пачка if с.get("created")]
        if not метки:
            return ""
        return datetime.fromtimestamp(max(метки), МСК).strftime("%d.%m.%Y")

    return {
        "наши": len(наши),
        "клиента": len(клиентские),
        "наше_последнее": когда(наши),
        "клиент_последний": когда(клиентские),
    }


def имя_собеседника(чат: dict, наш_id: int) -> str:
    for участник in чат.get("users") or []:
        if str(участник.get("id")) != str(наш_id):
            return str(участник.get("name") or "")
    return ""


def найти(ключ: str, порог: int = ПОРОГ) -> list[dict]:
    """Молчуны кабинета: клиент не написал ни разу, наших сообщений ≥ порога."""
    каб = реестр.кабинет(ключ)
    if not реестр.настроен(каб):
        print(f"[{ключ}] не настроен — пропускаю", flush=True)
        return []

    id_, secret = каб["переменные"]
    клиент = Avito(client_id=os.environ[id_], client_secret=os.environ[secret])
    находки: list[dict] = []
    try:
        наш_id = клиент.user_id
        чаты: list[dict] = []
        сдвиг = 0
        while True:
            порция = клиент.chats_list(limit=100, offset=сдвиг)
            чаты.extend(порция)
            if len(порция) < 100:
                break
            сдвиг += 100

        print(f"[{ключ}] чатов всего: {len(чаты)}", flush=True)
        for номер, чат in enumerate(чаты, 1):
            chat_id = чат.get("id")
            if not chat_id:
                continue
            try:
                сводка = разобрать_чат(все_сообщения(клиент, chat_id), наш_id)
            except Exception as ошибка:  # noqa: BLE001 — один чат не роняет ревизию
                print(f"[{ключ}] {chat_id}: не прочитался — {ошибка}", flush=True)
                continue
            if сводка["клиента"] == 0 and сводка["наши"] >= порог:
                находки.append(
                    {
                        "chat_id": chat_id,
                        "кабинет": ключ,
                        "название": каб["название"],
                        "имя": имя_собеседника(чат, наш_id),
                        "объявление": (
                            ((чат.get("context") or {}).get("value") or {}).get("title") or ""
                        ),
                        **сводка,
                    }
                )
            if номер % 50 == 0:
                print(f"[{ключ}] обработано {номер}/{len(чаты)}", flush=True)
    finally:
        клиент.close()
    return находки


def забраковать(находки: list[dict]) -> None:
    """Закрыть молчунов в Битриксе с причиной «не отвечает после дожима».

    Карточка ищется по ORIGIN_ID — привязке к чату. По имени не ищем
    намеренно: 01.09.2026 в воронке стояло 23 открытых сделки «Александр»
    и 13 «Дмитрий», а подстрока «Aleksa» подтягивала чужого «Aleksandr
    Nikolaevich». Не нашлось своей карточки — заводим сразу закрытую,
    иначе агент не увидит стоп-сигнала и продолжит писать.
    """
    b = Bitrix()
    try:
        for н in находки:
            подпись = (
                f"Ревизия молчунов {datetime.now(МСК):%d.%m.%Y}. "
                f"Чат {н['chat_id']}, {н['название']}, объявление «{н['объявление']}». "
                f"Наших сообщений: {н['наши']}, последнее {н['наше_последнее']}. "
                f"Ответов клиента: ни одного."
            )
            свои = b.crm_list(
                "deal",
                filter={"ORIGIN_ID": н["chat_id"]},
                select=["ID", "STAGE_ID"],
                limit=1,
            )
            if свои:
                b.crm_update(
                    "deal",
                    свои[0]["ID"],
                    {"STAGE_ID": "LOSE", "UF_CRM_FAIL_REASON": ПРИЧИНА_МОЛЧАНИЕ},
                )
                b.timeline_comment_add(свои[0]["ID"], подпись)
                print(f"  сделка {свои[0]['ID']} закрыта — {н['имя']}", flush=True)
                continue

            ид = b.crm_add(
                "deal",
                {
                    "TITLE": f"{н['имя'] or 'Без имени'} (Авито) — МОЛЧУН: "
                    f"{н['наши']} касаний без ответа",
                    "CATEGORY_ID": 0,
                    "STAGE_ID": "LOSE",
                    "UF_CRM_FAIL_REASON": ПРИЧИНА_МОЛЧАНИЕ,
                    "ORIGINATOR_ID": "avito",
                    "ORIGIN_ID": н["chat_id"],
                    "SOURCE_ID": "1|AVITO",
                    "COMMENTS": подпись,
                },
            )
            print(f"  заведена закрытая сделка {ид} — {н['имя']}", flush=True)
    finally:
        b.close()


def main() -> int:
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    закрывать = "--закрыть" in sys.argv

    порог = int(аргументы[0]) if аргументы else ПОРОГ
    ключи = [аргументы[1]] if len(аргументы) > 1 else list(реестр.КАБИНЕТЫ)

    все: list[dict] = []
    for ключ in ключи:
        все.extend(найти(ключ, порог))

    print(f"\nМОЛЧУНЫ (касаний ≥ {порог}, ответов ноль): {len(все)}\n", flush=True)
    for н in sorted(все, key=lambda x: -x["наши"]):
        print(
            f"  {н['наши']:3} касаний · {н['имя'][:28]:30} · {н['название'][:18]:20}"
            f" · последнее {н['наше_последнее']} · {н['chat_id']}",
            flush=True,
        )

    if закрывать and все:
        print("\nЗакрываю в Битриксе:", flush=True)
        забраковать(все)
    elif все:
        print("\nЧтобы забраковать их в Битриксе, добавь --закрыть", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
